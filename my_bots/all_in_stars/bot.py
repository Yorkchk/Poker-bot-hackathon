"""vf: equity vs likely hands + opponent profiles + adaptations to extreme styles.

Submission build of the frozen vf bot (github repo: poker_bot/versions/vf), generated by
tools/make_submission.py. The decision code is vf's, copied unchanged; only the file-based
memory is replaced by memory only, and an adapter for the tournament's game_state is added
at the end of this file.

How it decides (details in the repo's README):
  1. profiles: how each opponent usually plays (joins hands, raises, folds to bets...)
  2. likely hands: weights for the opponent's 1,326 possible hands, from its actions
  3. Monte Carlo: play the hand out many times against those likely hands -> equity
  4. raise if strong enough (stricter after each raise), call if equity beats the price,
     otherwise fold; special adjustments against maniacs, calling stations and folders
"""

