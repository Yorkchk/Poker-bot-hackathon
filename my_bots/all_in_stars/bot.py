# pokerbot/runtime/timebank.py
# =================================================================================================
"""Thinking-time management (the competition clock is unknown, so everything degrades gracefully).

- No clock information: river solves get `cap` seconds.
- With a match clock (time_left) and optionally the number of hands left, a river solve gets a share
  of the spendable time: (time_left - reserve) / expected remaining river decisions, scaled up for
  big pots (they matter more for chips) and capped. Below `min_solve` the agent does not solve and
  plays its blueprint river strategy instead (milliseconds).
- A hard per-decision limit (if the template has one) is respected with a safety factor.
"""



class TimeBank:
    def __init__(self, cap: float = 1.0, min_solve: float = 0.12, reserve_frac: float = 0.15,
                 reserve_abs: float = 2.0, river_rate: float = 0.35, default_hands_left: int = 500,
                 per_decision_limit: Optional[float] = None, safety: float = 0.6):
        self.cap = cap
        self.min_solve = min_solve
        self.reserve_frac = reserve_frac
        self.reserve_abs = reserve_abs
        self.river_rate = river_rate
        self.default_hands_left = default_hands_left
        self.per_decision_limit = per_decision_limit
        self.safety = safety

    def river_budget(self, time_left: Optional[float], hands_left: Optional[int], pot_bb: float) -> float:
        """Seconds to spend on a river solve (0 = do not solve)."""
        b = self.cap
        if time_left is not None:
            spendable = time_left - max(self.reserve_abs, self.reserve_frac * time_left)
            if spendable <= 0:
                return 0.0
            hl = hands_left if hands_left is not None else self.default_hands_left
            share = spendable / max(1.0, hl * self.river_rate)
            pot_weight = min(3.0, max(0.5, pot_bb / 20.0))       # ~20bb is a typical river pot
            b = min(b, share * pot_weight, 0.25 * spendable)
        if self.per_decision_limit is not None:
            b = min(b, self.safety * self.per_decision_limit)
        return b if b >= self.min_solve else 0.0


# =================================================================================================
# pokerbot/runtime/agent.py
# =================================================================================================
"""The competition agent.

v1 (river=False): plays the blueprint everywhere, translating off-tree opponent bets with the
    pseudo-harmonic map and realising its own abstract actions as pot fractions of the real pot.
v2 (river=True, default): river decisions are re-solved in real time (RiverSolver) from the exact
    real state (pot, stacks, the opponent's actual bet size) with both players' tracked ranges.
Ranges: Bayesian updates with the strategy actually used - the blueprint before the river, the
river solver's average strategy on the river (for both players' river actions after a solve).
Anything unexpected falls back safely (heuristic bot for the rest of the hand, or check/fold) -
the agent never crashes and never acts illegally.
"""






_BLUEPRINT_CACHE = {}


class _Tail:
    """Minimal observation used to process the end of a hand's history in end_hand()."""

    def __init__(self, history, board):
        self.history = tuple(history)
        self.board = tuple(board)


def load_blueprint(name: str) -> Blueprint:
    if name not in _BLUEPRINT_CACHE:
        _BLUEPRINT_CACHE[name] = Blueprint(data_dir() / "blueprints" / name / "export")
    return _BLUEPRINT_CACHE[name]


@register("agent")
class Agent(Bot):
    def __init__(self, blueprint: str = "bp_main", seed: int = 0, purify: float = 0.0, river: bool = True,
                 river_iters: int = 200, river_time: float = 1.0, river_purify: float = 0.03,
                 exploit: bool = False, exploit_min_obs: int = 30, exploit_margin: float = 1.0):
        self.bp = load_blueprint(blueprint)
        self.tables = get_tables()
        self.buckets = Buckets(self.tables, self.bp.meta["config"]["buckets"]["set"])
        self.rng = np.random.default_rng(seed)
        self.fallback = HeuristicBot(seed + 1)
        self.purify = purify
        self.river = river
        self.river_iters = river_iters
        self.river_time = river_time
        self.river_purify = river_purify
        self.river_sizes = RiverSizes()
        self.timebank = TimeBank(cap=river_time)
        self.exploit = exploit
        self.exploit_min_obs = exploit_min_obs
        self.exploit_margin = exploit_margin
        self.exploiter = Exploiter(self.tables, self.buckets, PreflopTables(), seed=seed + 2) if exploit else None
        self.model = OpponentModel()
        self.cfg = GameConfig()
        self.stats = {"decisions": 0, "fallback": 0, "errors": 0, "offtree_hands": 0, "river_solves": 0,
                      "exploit": 0}
        self.latency = []
        self.solve_log = []

    # -- match / hand hooks -------------------------------------------------------------------
    def new_match(self, cfg: GameConfig, seed: int) -> None:
        self.cfg = cfg
        self.rng = np.random.default_rng(seed)
        self.fallback.new_match(cfg, seed + 1)
        self.model = OpponentModel()

    def new_hand(self, hand_no: int, seat: int, button: int, hole) -> None:
        self.seat, self.button, self.hole = seat, button, (int(hole[0]), int(hole[1]))
        self.my_role = 0 if seat == button else 1            # abstract player 0 = button
        self.node = 0
        self.n_seen = 0
        self.off_tree = False        # lost track of the abstract tree (translation failure)
        self.detached = False        # deliberately left the abstract tree (river solver took over)
        self.pending = None
        self.solver = None
        self.solver_node = None
        self.real = HandState(self.cfg, button)
        self.ranges = [np.ones(NUM_COMBOS), np.ones(NUM_COMBOS)]   # by abstract role
        blocked = (COMBO_MASK & np.uint64(cards_mask(self.hole))) != 0
        self.ranges[1 - self.my_role][blocked] = 0.0
        self._bucket_cache = {}

    def end_hand(self, result: HandResult) -> None:
        # the action that ended the hand (often an opponent fold or call) was never seen by act()
        try:
            self._sync(_Tail(result.history, result.board))
        except Exception:
            self.stats["errors"] += 1
        if self.off_tree:
            self.stats["offtree_hands"] += 1
        self.model.hands += 1
        if result.showdown and result.opp_hole is not None:
            try:
                dead = list(self.hole) + list(result.board)
                valid = (COMBO_MASK & np.uint64(cards_mask(dead))) == 0
                oc = combo_index(result.opp_hole[0], result.opp_hole[1])
                strength = float(river_strengths(self.tables, result.board)[oc]) if len(result.board) == 5 else None
                n_raises = sum(1 for (_, seat, kind, _) in result.history if seat != self.seat and kind == RAISE)
                self.model.observe_showdown(self.ranges[1 - self.my_role], valid, oc, strength, n_raises)
            except Exception:
                pass

    def role_of(self, seat: int) -> int:
        return 0 if seat == self.button else 1

    # -- decisions ------------------------------------------------------------------------------
    def act(self, obs: Observation) -> Action:
        t0 = time.perf_counter()
        self.stats["decisions"] += 1
        try:
            self._sync(obs)
            budget = 0.0
            if self.river and obs.street == RIVER:
                budget = self.timebank.river_budget(obs.time_left, obs.hands_left, obs.pot / self.cfg.big_blind)
            if budget > 0:
                a = self._river_action(obs, budget)
            elif self.off_tree or self.detached or not self.bp.is_decision(self.node) or \
                    self.bp.player(self.node) != self.my_role:
                self.off_tree = True
                self.stats["fallback"] += 1
                self.pending = None
                a = self.fallback.act(obs)
            else:
                a = self._blueprint_action(obs)
            a = self._legalise(obs, a)
        except Exception:
            self.stats["errors"] += 1
            self.off_tree = True
            self.pending = None
            try:
                a = self._legalise(obs, self.fallback.act(obs))
            except Exception:
                a = obs.fold_or_check()
        self.latency.append(time.perf_counter() - t0)
        return a

    @staticmethod
    def _legalise(obs: Observation, a: Action) -> Action:
        if a.kind == FOLD:
            return a if obs.can_fold else Action(CALL)
        if a.kind == RAISE:
            if not obs.can_raise:
                return Action(CALL)
            return Action(RAISE, max(obs.min_raise_to, min(obs.max_raise_to, int(a.amount))))
        return Action(CALL)

    def _board_for(self, obs: Observation, street: int):
        return obs.board[:BOARD_CARDS[street]]

    def _all_buckets(self, obs: Observation, street: int) -> np.ndarray:
        if street not in self._bucket_cache:
            self._bucket_cache[street] = self.buckets.all(street, self._board_for(obs, street))
        return self._bucket_cache[street]

    def _apply_range(self, role: int, factor: np.ndarray) -> None:
        new = self.ranges[role] * factor
        if new.sum() > 1e-12 * max(self.ranges[role].sum(), 1e-300):
            self.ranges[role] = new

    def _bp_factor(self, node: int, obs: Observation, weights) -> np.ndarray:
        street = self.bp.street(node)
        probs = self.bp.probs_many(node, self._all_buckets(obs, street))
        f = np.zeros(NUM_COMBOS)
        for idx, w in weights:
            f += w * probs[:, idx]
        return f

    def _sync(self, obs: Observation) -> None:
        """Advance trackers (abstract node, solver node, real state, ranges) through new actions."""
        for entry in obs.history[self.n_seen:]:
            street, seat, kind, after = entry
            role = self.role_of(seat)
            state_before = self.real
            self.real = state_before.copy()
            self.real.apply(Action(kind, after if kind == RAISE else 0))
            self.n_seen += 1
            if role != self.my_role:
                self._observe_opponent(state_before, self.real, kind, after)
            if role == self.my_role:
                p, self.pending = self.pending, None
                if p is None:
                    self.off_tree = True
                    continue
                self._apply_range(role, p["vec"])
                if p["kind"] == "solver":
                    self.solver_node = self.solver.nodes[self.solver_node].children[p["idx"]]
                    self.detached = True                       # abstract tree no longer followed
                elif not (self.off_tree or self.detached):
                    self.node = self.bp.children(self.node)[p["idx"]]
                continue
            # opponent action
            if self.solver is not None and self.solver_node is not None and street == RIVER:
                sn = self.solver_node
                if self.solver.nodes[sn].kind != 0:
                    self.solver_node = None
                    continue
                mapped = self.solver.map_action(sn, kind, after)
                if not mapped:
                    self.solver_node = None
                    continue
                f = np.zeros(NUM_COMBOS)
                for idx, w in mapped:
                    f += w * self.solver.range_update(sn, idx)
                self._apply_range(role, f)
                best = max(mapped, key=lambda m: m[1])[0]
                self.solver_node = self.solver.nodes[sn].children[best]
                continue
            if self.off_tree or self.detached:
                continue
            if not self.bp.is_decision(self.node) or self.bp.player(self.node) != role:
                self.off_tree = True
                continue
            mapped = self._map_opponent(state_before, kind, after)
            if not mapped:
                self.off_tree = True
                continue
            self._apply_range(role, self._bp_factor(self.node, obs, mapped))
            r = self.rng.random()
            acc = 0.0
            pick = mapped[-1][0]
            for idx, w in mapped:
                acc += w
                if r < acc:
                    pick = idx
                    break
            self.node = self.bp.children(self.node)[pick]

    def _observe_opponent(self, before: HandState, after_state: HandState, kind: int, after: int) -> None:
        t = before.to_call()
        facing = size_class(t, before.pot - t, t > 0 and before.call_amount() >= before.stack_left(before.to_act))
        rcls = 0
        if kind == RAISE:
            t2 = after_state.to_call()
            rcls = size_class(t2, after_state.pot - t2, after >= after_state.cfg.stack)
        self.model.observe(before.street, facing, kind, rcls)

    def _map_opponent(self, s: HandState, kind: int, after: int):
        """[(child index, prob)] for an opponent action taken in real state `s`."""
        node = self.node
        if kind == FOLD:
            i, _ = self.bp.find_child(node, FOLD)
            return [(i, 1.0)] if i is not None else []
        if kind == CALL:
            i, _ = self.bp.find_child(node, CALL)
            return [(i, 1.0)] if i is not None else []
        raises = self.bp.raise_children(node)
        if not raises:
            return []
        me = s.to_act
        x = pot_fraction(after, s.contrib[me], s.contrib[1 - me])
        is_allin = after >= s.cfg.stack
        sizes = [r[2] for r in raises]
        allin_idx = next((j for j, r in enumerate(raises) if r[3]), -1)
        return [(raises[j][0], p) for j, p in map_size(x, sizes, allin_idx, is_allin)]

    def _leak_supports(self, obs: Observation, a: Action) -> bool:
        """Only clearly trivial opponent styles unlock exploitation (see OpponentModel.flags).

        Subtler leaks are not exploited: the showdown-approximation EV is too crude before the river
        and losing to competent rule-based bots costs more than it gains (measured in the arena).
        """
        flags = self.model.flags()
        if not flags:
            return False
        if a.kind == RAISE:
            return True                   # steal vs folders, value-bet big vs stations / maniacs
        return bool(flags & {"maniac", "folder", "station", "random"})

    def _sample(self, p: np.ndarray, purify: float) -> int:
        if purify > 0:
            q = np.where(p >= purify, p, 0.0)
            if q.sum() > 0:
                p = q / q.sum()
        return int(self.rng.choice(p.size, p=p / p.sum()))

    def _blueprint_action(self, obs: Observation) -> Action:
        node = self.node
        street = self.bp.street(node)
        if street != obs.street:
            raise RuntimeError("street misalignment")
        b = self.buckets.of(street, obs.board, obs.hole)
        p = self.bp.probs(node, b)
        acts = [self._legalise(obs, self._realise(obs, node, c)) for c in self.bp.children(node)]
        idx, action = self._choose(obs, acts, p, self.purify)
        self.pending = {"kind": "bp", "idx": idx, "vec": self._bp_factor(node, obs, [(idx, 1.0)])}
        return action

    def _choose(self, obs: Observation, acts, p: np.ndarray, purify: float):
        """Sample the equilibrium policy, or override it with a clearly better exploitative action.

        Returns (index into `acts` used for range tracking, action to play). Range tracking keeps
        following the equilibrium policy (the closest equilibrium action) so the river solver's view
        of our range stays consistent.
        """
        idx = self._sample(p, purify)
        if not self.exploit or self.model.decisions < self.exploit_min_obs:
            return idx, acts[idx]
        # (kit) the fold model is not conditioned on the hand: after the opponent raised in this hand,
        # deviate only if its raises carry no information (an over-folder's re-raise is the nuts)
        if any(seat == obs.opp and kind == RAISE for (_st, seat, kind, _amt) in obs.history) and \
                not (self.model.flags() & {"maniac", "random"}):
            return idx, acts[idx]
        cands = list(dict.fromkeys(list(acts) + candidate_raises(obs) + [Action(CALL)] +
                                   ([Action(FOLD)] if obs.can_fold else [])))
        ev = self.exploiter.evaluate(obs, self.ranges[1 - self.my_role], self.model, cands)
        ev_eq = sum(float(p[i]) * ev.get(a, 0.0) for i, a in enumerate(acts))
        allowed = [a for a in cands if a in acts or self._leak_supports(obs, a)]
        if not allowed:
            return idx, acts[idx]
        best = max(allowed, key=lambda a: ev.get(a, -1e18))
        if best in acts and not self._leak_supports(obs, best):
            return idx, acts[idx]           # re-weighting among equilibrium actions also needs a leak
        if ev[best] - ev_eq <= self.exploit_margin * MARGIN[obs.street] * obs.pot:
            return idx, acts[idx]
        self.stats["exploit"] += 1
        same = [i for i, a in enumerate(acts) if a.kind == best.kind]
        if not same:
            return idx, best
        return min(same, key=lambda i: abs(acts[i].amount - best.amount)), best

    def _realise(self, obs: Observation, node: int, child: int) -> Action:
        kind = self.bp.child_kind(child)
        if kind == FOLD:
            return Action(FOLD) if obs.can_fold else Action(CALL)
        if kind == CALL or not obs.can_raise:
            return Action(CALL)
        amt = int(self.bp._amount[child])
        if amt >= self.bp.cfg.stack:
            return Action(RAISE, obs.max_raise_to)
        me = self.bp.player(node)
        f = pot_fraction(amt, self.bp._contrib[node, me], self.bp._contrib[node, 1 - me])
        return Action(RAISE, obs.raise_to_for_fraction(f))

    # -- river solving ----------------------------------------------------------------------------
    def _seat_ranges(self, obs: Observation, ensure_combo=None):
        out = [None, None]
        board_blk = (COMBO_MASK & np.uint64(cards_mask(obs.board))) != 0
        for seat in (0, 1):
            r = self.ranges[self.role_of(seat)].copy()
            r[board_blk] = 0.0
            if r.sum() <= 0:          # degenerate tracking: fall back to all combos
                r = (~board_blk).astype(np.float64)
                if seat == obs.opp:
                    r[(COMBO_MASK & np.uint64(cards_mask(self.hole))) != 0] = 0.0
            out[seat] = r / r.sum()
        if ensure_combo is not None:
            me = out[obs.seat]
            me[ensure_combo] = max(me[ensure_combo], 1e-3 * me.max())
            out[obs.seat] = me / me.sum()
        return out

    def _solve_river(self, obs: Observation, root: HandState, ranges, budget: float) -> RiverSolver:
        solver = RiverSolver(self.tables, obs.board, root, ranges, self.river_sizes)
        solver.solve(self.river_iters, time_limit=budget)
        self.stats["river_solves"] += 1
        return solver

    def _river_action(self, obs: Observation, budget: float) -> Action:
        my_combo = combo_index(*self.hole)
        solver = self._solve_river(obs, self.real, self._seat_ranges(obs, my_combo), budget)
        self.solve_log.append((solver.iterations, solver.solve_seconds, len(solver.nodes), solver.w[0].size,
                               solver.w[1].size))
        acts = [self._legalise(obs, a) for a in solver.actions(0)]
        idx, action = self._choose(obs, acts, solver.hand_strategy(my_combo, 0), self.river_purify)
        self.solver, self.solver_node = solver, 0
        self.pending = {"kind": "solver", "idx": idx, "vec": solver.range_update(0, idx)}
        return action

    # -- white-box queries for evaluation (LBR); never change the agent's state ------------------
    def _save(self):
        return (self.node, self.n_seen, self.off_tree, self.detached, self.pending, self.real,
                [r.copy() for r in self.ranges], dict(self._bucket_cache), self.rng.bit_generator.state, self.solver,
                self.solver_node, dict(self.stats), self.model.snapshot())

    def _restore(self, s) -> None:
        (self.node, self.n_seen, self.off_tree, self.detached, self.pending, self.real, self.ranges,
         self._bucket_cache, state, self.solver, self.solver_node, self.stats, model_state) = s
        self.rng.bit_generator.state = state
        self.model.restore(model_state)

    def lbr_range(self, obs: Observation):
        """The agent's own range (float[1326]) after the actions in obs.history, or None if unknown."""
        saved = self._save()
        try:
            self._sync(obs)
            r = self.ranges[self.my_role]
            return r.copy() if r.sum() > 0 else None
        finally:
            self._restore(saved)

    def lbr_fold_probs(self, obs: Observation, opp_action: Action):
        """P(agent folds | combo) right after the opponent takes `opp_action` in the state of `obs`."""
        saved = self._save()
        try:
            self._sync(obs)
            if self.river and obs.street == RIVER:
                return self._lbr_fold_river(obs, opp_action)
            if self.off_tree or self.detached or not self.bp.is_decision(self.node):
                return None
            mapped = self._map_opponent(self.real, opp_action.kind, opp_action.amount)
            if not mapped:
                return None
            fold = np.zeros(NUM_COMBOS)
            for idx, w in mapped:
                child = self.bp.children(self.node)[idx]
                if not self.bp.is_decision(child) or self.bp.player(child) != self.my_role:
                    continue
                fi, _ = self.bp.find_child(child, FOLD)
                if fi is None:
                    continue
                probs = self.bp.probs_many(child, self._all_buckets(obs, self.bp.street(child)))
                fold += w * probs[:, fi]
            return fold
        finally:
            self._restore(saved)

    def _lbr_fold_river(self, obs: Observation, opp_action: Action):
        """Solve the river spot the agent would face after the hypothetical opponent action."""
        opp_role = 1 - self.my_role
        if not self.off_tree and self.bp.is_decision(self.node) and self.bp.player(self.node) == opp_role:
            mapped = self._map_opponent(self.real, opp_action.kind, opp_action.amount)
            if mapped:
                self._apply_range(opp_role, self._bp_factor(self.node, obs, mapped))
        after = self.real.copy()
        after.apply(opp_action)
        if after.finished:
            return np.zeros(NUM_COMBOS)
        fake = Observation(obs.cfg, obs.hand_no, self.seat, obs.button, self.hole, obs.board, after.street,
                           tuple(after.contrib), tuple(after.street_start), after.can_fold(), after.call_amount(),
                           None, None, obs.history, obs.time_left)
        solver = self._solve_river(fake, after, self._seat_ranges(fake), self.river_time)
        fi = next((i for i, a in enumerate(solver.actions(0)) if a.kind == FOLD), None)
        if fi is None:
            return np.zeros(NUM_COMBOS)
        return solver.range_update(0, fi)


