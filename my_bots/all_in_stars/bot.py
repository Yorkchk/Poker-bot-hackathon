"""Lever 2: 'hats' - how v2 changes its own play against clearly weak opponents.

Lever 1 (ranges.py) changes what v2 believes an opponent holds. Hats change what
v2 does with that belief. Each opponent wears at most one hat, chosen from its
profile (profiles.py), and only with enough evidence. Decent bots wear none.

  maniac   raises very often, or plays most hands and raises a lot
           -> its bets/raises are not treated as strength (lever 1 barely
              narrows its hands), its raises don't count for the re-raise
              rule, v2 calls it down lighter and value-bets bigger
  station  joins many hands and rarely folds   -> bet medium hands for value,
           bigger bets, no semi-bluffs
  folder   folds to bets very often            -> small bluffs when checked to,
           smaller value bets

Bots can change style, so every stat is checked twice (profiles.py):
  * a hat goes ON only when BOTH the long-memory and the short-memory stats pass
    the 'on' threshold
  * it comes OFF as soon as the short-memory stats fall past the looser 'off'
    threshold, so a changed bot loses its hat within a few dozen hands
"""

DEFAULT = None
MANIAC, STATION, FOLDER = "maniac", "station", "folder"

MIN_HANDS = 30            # no hat before this many hands seen with that opponent
MIN_FOLD_CHANCES = 40     # the folder hat also needs this many 'facing a bet' chances

# Each hat: a list of alternatives; an alternative is a list of
# (stat, on-threshold, off-threshold, direction) conditions that must all hold.
# Field test reference: decent bots join 17-30% of hands, raise 4-22% and fold to
# bets 17-65%; the folder bot folds to 54-75%, the bluffer joins 44% and folds to 19%,
# the random bot joins 65% and raises 37%, the always-raise bot raises 98%.
RULES = {
    MANIAC:  [[("pfr", 0.50, 0.45, ">")],
              [("vpip", 0.50, 0.45, ">"), ("pfr", 0.30, 0.25, ">")]],
    STATION: [[("vpip", 0.40, 0.35, ">"), ("fold_to_bet", 0.25, 0.30, "<")]],
    FOLDER:  [[("fold_to_bet", 0.70, 0.65, ">")]],
}
ORDER = [MANIAC, STATION, FOLDER]   # first match wins


def _check(value, limit, direction):
    return value > limit if direction == ">" else value < limit


def _passes(profile, hat, keep):
    if hat == FOLDER and profile.chances["fold_to_bet"] < MIN_FOLD_CHANCES:
        return False
    for alternative in RULES[hat]:
        ok = True
        for stat, on, off, direction in alternative:
            if keep:   # staying on: only the recent behaviour matters
                ok = _check(profile.get_recent(stat), off, direction)
            else:      # switching on: long and recent memory must agree
                ok = (_check(profile.get(stat), on, direction)
                      and _check(profile.get_recent(stat), on, direction))
            if not ok:
                break
        if ok:
            return True
    return False


def choose_hat(profile, current=DEFAULT):
    """Hat for one opponent, given its profile and the hat it wore last time."""
    if profile.hands < MIN_HANDS:
        return DEFAULT
    if current and _passes(profile, current, keep=True):
        return current                      # stays on until it clearly changed
    for hat in ORDER:
        if _passes(profile, hat, keep=False):
            return hat
    return DEFAULT


