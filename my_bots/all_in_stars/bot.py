class Buckets:
    """Same interface as core/buckets.py. Flop/turn: the training tables. River: the training rule
    (equal-mass EHS percentiles, build_buckets.river_buckets) applied to the exact EHS of the board,
    which reproduces river_bucket.npy without shipping it."""

    def __init__(self, tables: Tables, set_name: str):
        d = tables.dir / set_name
        self.set_name = set_name
        self.tables = tables
        self.street_tables = {}
        for street, name in ((FLOP, "flop"), (TURN, "turn")):
            with np.load(d / f"{name}_bucket.npz") as z:
                self.street_tables[street] = z["bucket"]
        meta = json.loads((d / "buckets_meta.json").read_text())
        self.river_codes = np.rint(np.asarray(meta["river_thresholds"], dtype=np.float64) * EHS_SCALE
                                   ).astype(np.int64)
        self._river_key = None
        self._river_row = None

    def river_row(self, board) -> np.ndarray:
        key = tuple(sorted(int(c) for c in board))
        if key != self._river_key:
            ehs = river_strengths(self.tables, key)            # NaN where the combo overlaps the board
            ok = ~np.isnan(ehs)
            code = np.floor(np.where(ok, ehs, 0.0) * EHS_SCALE + 0.5).astype(np.int64)
            row = np.searchsorted(self.river_codes, code, side="right").astype(np.int64)
            row[~ok] = INVALID
            self._river_key, self._river_row = key, row
        return self._river_row

    def of(self, street: int, board, hole) -> int:
        h = combo_index(hole[0], hole[1])
        if street == PREFLOP:
            return int(PREFLOP_CLASS[h])
        if street == RIVER:
            return int(self.river_row(board)[h])
        cid, p = self.tables.canon(board)
        return int(self.street_tables[street][cid, PERM_COMBO[p, h]])

    def all(self, street: int, board) -> np.ndarray:
        """int64[1326] bucket of every combo (65535 where the combo overlaps the board)."""
        if street == PREFLOP:
            return PREFLOP_CLASS.astype(np.int64)
        if street == RIVER:
            return self.river_row(board).copy()
        cid, p = self.tables.canon(board)
        row = np.asarray(self.street_tables[street][cid])
        return row[PERM_COMBO[p]].astype(np.int64)


