def has_made_hand(hole, board):
    """True if our hole cards make at least a real pair with the board
    (a pair that only sits on the board doesn't count)."""
    if len(board) < 3:
        return True
    cat = category(evaluate(list(hole) + list(board)))
    if cat >= TWO_PAIR:
        return True
    if cat == PAIR:
        hole_ranks = {c >> 2 for c in hole}
        board_ranks = [c >> 2 for c in board]
        paired = hole_ranks & set(board_ranks) or (len(hole_ranks) == 1)
        return bool(paired)
    return False


class BotVF:
    """Frozen vf: same play as v2 on 2026-11-19."""

    def __init__(self, name="vf", config=None, rng=None, history_dir=None, **_ignored):
        """history_dir: folder for the hand history JSON files (None = memory only)."""
        self.name = name
        self.config = dict(CONFIG_VF, **(config or {}))
        self.rng = rng or random.Random()
        self.profiles = Profiles(me=name)
        self.ranges = RangeBuilder()
        self.hats = {}                  # opponent -> hat it currently wears
        self.hat_uses = Counter()       # how often each hat shaped a decision (for tests)
        self.short_stack_moves = Counter()   # how often the short-stack mode decided (for tests)
        self.history = HandHistory(history_dir, me=name, on_finish=self._learn)
        self._restoring = True
        self.restored_from = self._restore()        # "memory", "snapshot" or "replay"
        self._restoring = False

    # ------------------------------------------------------------ memory
    # Submission build: memory only. The tournament forbids file writes and starts a
    # fresh process for every match; the adapter at the end of this file feeds every
    # finished hand from the match log into the profiles through _learn().
    def _restore(self):
        return "memory"

    def _learn(self, hand):
        try:
            self.profiles.add_hand(hand)
        except Exception:
            pass

    def decide(self, state):
        """Safety wrapper: whatever happens, return a legal action."""
        try:
            self.history.observe(state)
        except Exception:
            pass   # recording must never stop us from playing
        try:
            return make_legal(state, self._decide(state))
        except Exception:
            return vf_Action(CHECK) if state.to_call == 0 else vf_Action(vf_FOLD)

    def end_hand(self, info):
        """Called by the game after each hand, if it supports that."""
        try:
            self.history.end_hand(info)
        except Exception:
            pass

    def opponent_ranges(self, state):
        if not self.config["use_ranges"]:
            return None
        try:
            hats = self.hats if self.config["use_hats"] else None
            weights = self.ranges.build(state, self.profiles, hats=hats,
                                        maniac_trust=self.config["maniac_range_trust"])
        except Exception:
            return None
        if not weights:
            return None
        return list(weights.values())

    def _decide(self, state):
        cfg = self.config
        if cfg["use_short_stack"]:
            move = short_stack_move(state, cfg)     # all-in or fold when short before the flop
            if move:
                self.short_stack_moves[move] += 1
            if move == ALLIN:
                return vf_Action(vf_RAISE, state.max_raise_to)
            if move == SS_FOLD:
                return vf_Action(vf_FOLD)
            if move == SS_CHECK:
                return vf_Action(CHECK)
        n = max(1, state.num_opponents)
        t0 = time.perf_counter()
        # Lever 2 first: which hat (if any) applies? Lever 1 needs the hats too
        # (a maniac's bets barely narrow its likely hands).
        hat, maniacs = self.hat_for(state)
        self.hat_uses[hat or "default"] += 1
        ranges = self.opponent_ranges(state)
        budget = max(0.03, cfg["time_budget"] - (time.perf_counter() - t0))   # ranges eat into the budget
        equity, _ = monte_carlo_equity(
            state.hole_cards, state.board, n,
            iterations=cfg["iterations"], time_budget=budget, rng=self.rng, ranges=ranges,
        )
        strength = equity * (n + 1)   # 1.0 = exactly a fair share
        pot_odds = state.to_call / (state.pot + state.to_call) if state.to_call else 0.0
        can_raise = vf_RAISE in legal_kinds(state)

        # Step 2a: how many raises already happened on this street?
        # (a maniac's raises don't count: they say nothing about its hand)
        if state.actions:
            raises = sum(1 for c in vf_replay(state.actions)
                         if c["street"] == state.street and c["action"] == "raise"
                         and c["player"] not in maniacs)
        elif state.street == "preflop":
            raises = 1 if state.current_bet > state.big_blind else 0
        else:
            raises = 1 if state.current_bet > 0 else 0
        ratios = cfg["raise_ratios"]
        raise_needed = ratios[min(raises, len(ratios) - 1)]
        raise_size, big_size = cfg["raise_size"], cfg["big_raise_size"]
        call_margin = cfg["call_margin"]
        if hat == STATION:
            if raises == 0:
                raise_needed = min(raise_needed, cfg["station_raise_ratio"])
            raise_size, big_size = cfg["station_size"], cfg["station_big_size"]
        elif hat == MANIAC:
            call_margin = cfg["maniac_call_margin"]
            if raises == 0:      # only maniac raises so far this street
                raise_needed = min(raise_needed, cfg["maniac_raise_ratio"])
            raise_size, big_size = cfg["maniac_size"], cfg["maniac_big_size"]
        elif hat == FOLDER:
            raise_size = big_size = cfg["folder_value_size"]

        # Step 2b: a draw (no real hand yet, before the river) never raises big.
        drawing = state.street in ("flop", "turn") and not has_made_hand(state.hole_cards, state.board)
        pot_after_call = state.pot + state.to_call

        if can_raise and strength >= raise_needed:
            if drawing:
                if raises == 0 and hat != STATION:   # semi-bluff (pointless vs a station)
                    return vf_Action(vf_RAISE, max(state.min_raise_to,
                                             state.current_bet + int(cfg["draw_bet_size"] * pot_after_call)))
            else:
                big = strength >= max(cfg["big_raise_ratio"], raise_needed)
                size = big_size if big else raise_size
                raise_to = state.current_bet + int(size * pot_after_call)
                raise_to = max(raise_to, state.min_raise_to)
                # Raising most of our stack? Then just go all-in.
                if raise_to - state.my_bet >= cfg["commit_fraction"] * state.stack:
                    raise_to = state.max_raise_to
                return vf_Action(vf_RAISE, raise_to)

        if state.to_call == 0:
            if (hat == FOLDER and can_raise and state.street != "preflop"
                    and self.rng.random() < cfg["folder_bluff_rate"]):
                return vf_Action(vf_RAISE, max(state.min_raise_to, int(cfg["folder_bluff_size"] * state.pot)))
            return vf_Action(CHECK)
        if equity > pot_odds + call_margin:
            return vf_Action(vf_CALL)
        return vf_Action(vf_FOLD)

    def hat_for(self, state):
        """Return (hat for this decision, set of opponents wearing the maniac hat).

        The hat of the opponent we're mainly playing against: the last raiser this
        street when facing a bet, the only opponent when heads-up, otherwise a hat
        all remaining opponents share. Anything else -> default play."""
        if not self.config["use_hats"] or not state.players:
            return None, set()
        alive = [p["id"] for p in state.players if not p.get("folded") and p["id"] != state.my_id]
        hats = {}
        for p in alive:
            hats[p] = choose_hat(self.profiles.get(p), self.hats.get(p))
            self.hats[p] = hats[p]
        maniacs = {p for p, h in hats.items() if h == MANIAC}
        if state.to_call > 0 and state.actions:
            last_raiser = None
            for c in vf_replay(state.actions):
                if c["street"] == state.street and c["action"] == "raise":
                    last_raiser = c["player"]
            if last_raiser in hats:
                return hats[last_raiser], maniacs
        if len(alive) == 1:
            return hats[alive[0]], maniacs
        distinct = set(hats.values())
        return (distinct.pop() if len(distinct) == 1 else None), maniacs


