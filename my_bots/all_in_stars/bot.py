# versions/vf/short_stack.py
# ============================================================================
"""Short-stack mode: all-in or fold before the flop.

In a last-bot-standing tournament the blinds keep growing, so the end of every
tournament is played with short stacks. With few big blinds left, raising small
and folding to a re-raise, or calling and folding the flop, wastes chips that
are a big share of the stack. Standard short-stack play is all-in or fold.

Applies only before the flop, when the effective stack (our chips vs the biggest
stack still in the hand) is at most `short_stack_bb` big blinds:

  nobody raised yet        all-in with the top `share` of starting hands, else
                           fold (or check a free big blind)
  someone raised, not      re-raise all-in with a tighter share
  all-in                   (share x reshove_factor), else fold; never just call
  someone is all-in        None: v2's normal logic decides (call only if its win
                           chance against the shover's likely hands beats the price)

`share` widens as the stack shrinks and as fewer opponents can still call:
  share = min(0.95, push_base + push_depth / stack_in_bb) * push_per_player ** (opponents - 1)
e.g. 10 bb: ~58% heads-up (small blind vs big blind), ~33% with 3 opponents left,
~10% with 7 opponents left; 5 bb: ~86% heads-up.
"""


ALLIN, FOLD, CHECK = "allin", "fold", "check"


def _q(hole):
    a, b = sorted(hole)
    return PREFLOP_Q[COMBOS.index((a, b))]


def effective_bb(state):
    mine = state.stack + state.my_bet
    others = [p["stack"] + p.get("bet", 0) for p in state.players or []
              if not p.get("folded") and p["id"] != state.my_id]
    eff = min(mine, max(others)) if others else mine
    return eff / state.big_blind


def push_share(depth_bb, opponents, cfg):
    base = min(0.95, cfg["push_base"] + cfg["push_depth"] / max(depth_bb, 1.0))
    share = base * cfg["push_per_player"] ** max(0, opponents - 1)
    return max(0.03, min(0.95, share))


def short_stack_move(state, cfg):
    """ALLIN, FOLD or CHECK, or None when the normal logic should decide."""
    if state.street != "preflop":
        return None
    depth = effective_bb(state)
    if depth > cfg["short_stack_bb"]:
        return None
    if state.to_call >= state.stack:
        return None                          # calling already puts us all-in: normal logic
    alive = [p for p in state.players or [] if not p.get("folded") and p["id"] != state.my_id]
    if any(p["stack"] == 0 for p in alive):
        return None                          # facing an all-in: normal logic (equity vs price)
    raises = sum(1 for c in replay(state.actions or [])
                 if c["street"] == "preflop" and c["action"] == "raise")
    opponents = max(1, state.num_opponents)
    share = push_share(depth, opponents, cfg)
    if raises:
        share *= cfg["reshove_factor"]
    if _q(state.hole_cards) >= 1 - share:
        return ALLIN
    return CHECK if state.to_call == 0 else FOLD


