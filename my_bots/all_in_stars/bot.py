def has_made_hand(hole, board):
    """True if our hole cards make at least a real pair with the board
    (a pair that only sits on the board doesn't count)."""
    if len(board) < 3:
        return True
    cat = category(evaluate(list(hole) + list(board)))
    if cat >= TWO_PAIR:
        return True
    if cat == PAIR:
        hole_ranks = {c >> 2 for c in hole}
        board_ranks = [c >> 2 for c in board]
        paired = hole_ranks & set(board_ranks) or (len(hole_ranks) == 1)
        return bool(paired)
    return False


