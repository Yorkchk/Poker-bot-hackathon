class Blueprint:
    def __init__(self, path):
        path = Path(path)
        self.path = path
        self.tree = FlatTree.load(path)
        self.strat = load_strategy(path)                # (kit) compressed file, held in memory
        self.meta = json.loads((path / "meta.json").read_text())
        g = self.meta["config"]["game"]
        self.cfg = GameConfig(g["small_blind"], g["big_blind"], g["stack"])
        t = self.tree
        self._node_type = t.node_type
        self._nact = t.nact.astype(np.int64)
        self._child0 = t.child0.astype(np.int64)
        self._slot = t.slot
        self._kind = t.action_kind
        self._amount = t.action_amount.astype(np.int64)
        self._contrib = t.contrib.astype(np.int64)
        self._player = t.player

    # -- tree navigation ------------------------------------------------------------------
    def is_decision(self, node: int) -> bool:
        return node >= 0 and self._node_type[node] == DECISION

    def player(self, node: int) -> int:
        return int(self._player[node])

    def street(self, node: int) -> int:
        return int(self.tree.street[node])

    def children(self, node: int) -> range:
        c0 = int(self._child0[node])
        return range(c0, c0 + int(self._nact[node]))

    def child_kind(self, child: int) -> int:
        return int(self._kind[child])

    def find_child(self, node: int, kind: int):
        for i, c in enumerate(self.children(node)):
            if self._kind[c] == kind:
                return i, c
        return None, None

    def raise_children(self, node: int):
        """[(action index, child, pot fraction, is_allin)] of the raise actions at `node`, by size."""
        me = self.player(node)
        cm, co = self._contrib[node, me], self._contrib[node, 1 - me]
        out = []
        for i, c in enumerate(self.children(node)):
            if self._kind[c] == RAISE:
                amt = int(self._amount[c])
                out.append((i, c, pot_fraction(amt, cm, co), amt >= self.cfg.stack))
        return out

    # -- strategy lookups -----------------------------------------------------------------
    def probs(self, node: int, bucket: int) -> np.ndarray:
        n = int(self._nact[node])
        base = int(self._slot[node]) + int(bucket) * n
        q = np.asarray(self.strat[base:base + n], dtype=np.float64)
        s = q.sum()
        return q / s if s > 0 else np.full(n, 1.0 / n)

    def probs_many(self, node: int, buckets: np.ndarray) -> np.ndarray:
        """(len(buckets), nact) strategy rows; invalid buckets (65535) give uniform rows."""
        n = int(self._nact[node])
        b = np.asarray(buckets, dtype=np.int64)
        ok = b != 65535
        bb = np.where(ok, b, 0)
        idx = int(self._slot[node]) + bb[:, None] * n + np.arange(n)
        q = np.asarray(self.strat[idx.ravel()], dtype=np.float64).reshape(b.size, n)
        s = q.sum(axis=1, keepdims=True)
        p = np.where(s > 0, q / np.where(s > 0, s, 1.0), 1.0 / n)
        p[~ok] = 1.0 / n
        return p


