# pokerbot/runtime/opponent.py
# =================================================================================================
"""Opponent model for one match (pure NumPy).

What is tracked
- Action frequencies per situation (street, size class of the bet faced): Dirichlet counts over
  {fold, call/check, raise}, shrunk toward the opponent's own street/global rates and a population prior
  (hierarchical smoothing), so a few hands already give usable estimates.
- Range informativeness lambda: how much the opponent's actions reveal about its cards. At each
  showdown we know the Bayesian range our tracker held for the opponent and the hand it actually had;
  lambda maximises the likelihood of the revealed hands under (lambda * tracked + (1-lambda) * uniform).
  GTO-like bots -> lambda near 1; random bots and calling stations -> lambda near 0.
"""




A_FOLD, A_CALL, A_RAISE = 0, 1, 2
SIZE_NONE, SIZE_SMALL, SIZE_MED, SIZE_LARGE, SIZE_OVER, SIZE_ALLIN = 0, 1, 2, 3, 4, 5
SIZE_NAMES = ("none", "small", "medium", "large", "overbet", "allin")

# population prior P(fold | facing size class): roughly minimum-defence-frequency play, slightly looser
_PRIOR_FOLD = {SIZE_SMALL: 0.25, SIZE_MED: 0.38, SIZE_LARGE: 0.48, SIZE_OVER: 0.58, SIZE_ALLIN: 0.62}
_PRIOR_RAISE = {SIZE_NONE: 0.35, SIZE_SMALL: 0.12, SIZE_MED: 0.10, SIZE_LARGE: 0.08, SIZE_OVER: 0.05,
                SIZE_ALLIN: 0.0}


def size_class(to_call: float, pot_before_bet: float, is_allin: bool) -> int:
    """Class of a bet of `to_call` chips into `pot_before_bet` (pot before the bet was made)."""
    if to_call <= 0:
        return SIZE_NONE
    if is_allin:
        return SIZE_ALLIN
    f = to_call / max(pot_before_bet, 1e-9)
    if f <= 0.4:
        return SIZE_SMALL
    if f <= 0.8:
        return SIZE_MED
    if f <= 1.5:
        return SIZE_LARGE
    return SIZE_OVER


def street_group(street: int) -> int:
    return 0 if street == PREFLOP else 1


class OpponentModel:
    def __init__(self, prior_strength: float = 4.0, lambda_prior: float = 0.8, lambda_strength: float = 6.0,
                 reference: dict = None):
        self.prior_strength = prior_strength
        self.reference = reference        # equilibrium action frequencies (blueprint self-play), optional
        self.counts = defaultdict(lambda: np.zeros(3))      # (street_group, size_class) -> [fold, call, raise]
        self.street_counts = defaultdict(lambda: np.zeros(3))
        self.total = np.zeros(3)
        self.raise_sizes = defaultdict(lambda: np.zeros(6))  # street_group -> histogram of raise size classes
        self.decisions = 0
        self.lambda_prior = lambda_prior
        self.lambda_strength = lambda_strength
        self._sd_bayes = []     # probability the tracked range gave to the revealed hand
        self._sd_uniform = []
        self._sd_strength = []  # opponent's final hand strength at showdowns
        self._sd_raises = []    # number of opponent raises in those hands
        self.hands = 0

    # -- observations -------------------------------------------------------------------------
    def observe(self, street: int, facing: int, action_kind: int, raise_class: int = SIZE_NONE) -> None:
        a = A_FOLD if action_kind == FOLD else (A_CALL if action_kind == CALL else A_RAISE)
        g = street_group(street)
        self.counts[(g, facing)][a] += 1
        self.street_counts[(g, facing > 0)][a] += 1
        self.total[a] += 1
        self.decisions += 1
        if a == A_RAISE:
            self.raise_sizes[g][raise_class] += 1

    def observe_showdown(self, tracked_range: np.ndarray, valid: np.ndarray, combo: int,
                         strength: float = None, n_raises: int = None) -> None:
        r = np.asarray(tracked_range, dtype=np.float64) * valid
        u = valid.astype(np.float64)
        if strength is not None and n_raises is not None:
            self._sd_strength.append(float(strength))
            self._sd_raises.append(float(n_raises))
        if r.sum() <= 0 or u.sum() <= 0:
            return
        self._sd_bayes.append(float(r[combo] / r.sum()))
        self._sd_uniform.append(float(u[combo] / u.sum()))

    def strength_aggression_corr(self):
        """Correlation between revealed hand strength and how often the opponent raised in that hand."""
        if len(self._sd_strength) < 15:
            return None
        s = np.array(self._sd_strength)
        k = np.array(self._sd_raises)
        if s.std() < 1e-9 or k.std() < 1e-9:
            return 0.0
        return float(np.corrcoef(s, k)[0, 1])

    # -- estimates ----------------------------------------------------------------------------
    def action_probs(self, street: int, facing: int) -> np.ndarray:
        """Posterior mean of P(fold, call, raise) in a situation (hierarchically smoothed)."""
        g = street_group(street)
        if facing == SIZE_NONE:
            prior = np.array([0.0, 1.0 - _PRIOR_RAISE[SIZE_NONE], _PRIOR_RAISE[SIZE_NONE]])
        else:
            pf, pr = _PRIOR_FOLD[facing], _PRIOR_RAISE[facing]
            prior = np.array([pf, 1.0 - pf - pr, pr])
        k = self.prior_strength
        # level 1: opponent's global facing/not-facing rates temper the population prior
        sc = self.street_counts[(g, facing > 0)]
        if sc.sum() > 0:
            emp = sc / sc.sum()
            w = sc.sum() / (sc.sum() + k)
            prior = (1 - w) * prior + w * emp
            if facing == SIZE_NONE:
                prior[A_FOLD] = 0.0
                prior /= prior.sum()
        c = self.counts[(g, facing)]
        post = (c + k * prior) / (c.sum() + k)
        return post

    def fold_prob(self, street: int, facing: int) -> float:
        return float(self.action_probs(street, facing)[A_FOLD]) if facing != SIZE_NONE else 0.0

    def observations(self, street: int, facing: int) -> float:
        return float(self.counts[(street_group(street), facing)].sum())

    def range_lambda(self) -> float:
        """MAP mixture weight of the tracked range vs uniform, from revealed showdown hands."""
        if not self._sd_bayes:
            return self.lambda_prior
        b = np.array(self._sd_bayes)
        u = np.array(self._sd_uniform)
        grid = np.linspace(0.0, 1.0, 51)
        a0 = self.lambda_prior * self.lambda_strength
        b0 = (1 - self.lambda_prior) * self.lambda_strength
        best, best_ll = self.lambda_prior, -math.inf
        for lam in grid:
            ll = float(np.log(lam * b + (1 - lam) * u + 1e-300).sum())
            lam_c = min(max(lam, 1e-3), 1 - 1e-3)
            ll += (a0 - 1) * math.log(lam_c) + (b0 - 1) * math.log(1 - lam_c)   # Beta prior
            if ll > best_ll:
                best, best_ll = lam, ll
        return float(best)

    # -- leak detection (gates exploitation) -----------------------------------------------------
    def reference_fold(self, facing: int) -> float:
        return _PRIOR_FOLD.get(facing, 0.0) if self.reference is None else \
            self.reference.get(f"fold_{facing}", _PRIOR_FOLD.get(facing, 0.0))

    def reference_raise(self, street: int, facing_bet: bool) -> float:
        key = f"raise_{street_group(street)}_{int(facing_bet)}"
        default = _PRIOR_RAISE[SIZE_SMALL] if facing_bet else _PRIOR_RAISE[SIZE_NONE]
        return default if self.reference is None else self.reference.get(key, default)

    @staticmethod
    def _significant(k: float, n: float, ref: float, tol: float, z: float) -> float:
        if n < 12:
            return 0.0
        p = k / n
        se = math.sqrt(max(ref * (1 - ref), 0.02) / n)
        d = p - ref
        return d if abs(d) > tol and abs(d) / se > z else 0.0

    def fold_leak(self, street: int, facing: int, tol: float = 0.12, z: float = 2.5) -> float:
        """Signed deviation of the opponent's fold rate vs the reference when facing this bet class
        (0 if not significant). Neighbouring size classes are pooled when data is thin."""
        g = street_group(street)
        c = self.counts[(g, facing)].copy()
        if c.sum() < 12:
            for nb in (facing - 1, facing + 1):
                if SIZE_SMALL <= nb <= SIZE_ALLIN:
                    c += self.counts[(g, nb)]
        return self._significant(c[A_FOLD], c.sum(), self.reference_fold(facing), tol, z)

    def raise_leak(self, street: int, facing_bet: bool, tol: float = 0.15, z: float = 2.5) -> float:
        c = self.street_counts[(street_group(street), facing_bet)]
        return self._significant(c[A_RAISE], c.sum(), self.reference_raise(street, facing_bet), tol, z)

    def uninformative(self, max_lambda: float = 0.45, min_showdowns: int = 10) -> bool:
        return len(self._sd_bayes) >= min_showdowns and self.range_lambda() <= max_lambda

    def facing_bet_rates(self):
        c = self.street_counts[(0, True)] + self.street_counts[(1, True)]
        n = c.sum()
        return (c[A_FOLD] / n if n else 0.0), (c[A_RAISE] / n if n else 0.0), n

    def flags(self) -> set:
        """Clearly identified trivial styles (only these unlock exploitation).

        station: almost never folds to a bet; folder: folds most of the time to a bet;
        maniac: raises very often and its revealed hands show the raises carry little information.
        """
        out = set()
        fold_rate, _, n_facing = self.facing_bet_rates()
        if n_facing >= 25 and fold_rate <= 0.06:
            out.add("station")
        if n_facing >= 20 and fold_rate >= 0.80:
            out.add("folder")
        tot = self.total.sum()
        if tot >= 30 and self.total[A_RAISE] / tot >= 0.40 and self.uninformative(0.5, 12):
            out.add("maniac")
        # raises a lot, its raises say nothing about its cards, and its showdowns contradict our tracked
        # ranges (balanced strategies also bluff, but they keep lambda high, so they are excluded)
        corr = self.strength_aggression_corr()
        if (corr is not None and corr < 0.08 and len(self._sd_strength) >= 25 and tot >= 40
                and self.total[A_RAISE] / tot >= 0.25 and self.uninformative(0.5, 20)):
            out.add("random")
        return out

    def snapshot(self):
        """Copy of the mutable counters (white-box queries must not change the model)."""
        return ({k: v.copy() for k, v in self.counts.items()}, {k: v.copy() for k, v in self.street_counts.items()},
                self.total.copy(), {k: v.copy() for k, v in self.raise_sizes.items()}, self.decisions,
                list(self._sd_bayes), list(self._sd_uniform), list(self._sd_strength), list(self._sd_raises),
                self.hands)

    def restore(self, s) -> None:
        counts, street_counts, total, raise_sizes, self.decisions, b, u, st, rz, self.hands = s
        self.counts = defaultdict(lambda: np.zeros(3), counts)
        self.street_counts = defaultdict(lambda: np.zeros(3), street_counts)
        self.total = total
        self.raise_sizes = defaultdict(lambda: np.zeros(6), raise_sizes)
        self._sd_bayes, self._sd_uniform, self._sd_strength, self._sd_raises = b, u, st, rz

    def summary(self) -> dict:
        tot = self.total.sum()
        return {"decisions": self.decisions, "fold": self.total[0] / max(tot, 1), "call": self.total[1] / max(tot, 1),
                "raise": self.total[2] / max(tot, 1), "lambda": self.range_lambda(), "showdowns": len(self._sd_bayes)}


