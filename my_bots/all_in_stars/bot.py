"""Heads-up no-limit hold'em rules (pure Python; shared by arena, tree builder, LBR and adapter).

Conventions
- Integer chips. Both players start every hand with cfg.stack (stacks reset each hand).
- Seat `button` posts the small blind, acts first preflop and last postflop.
- A RAISE carries `amount` = the raiser's TOTAL contribution for the hand after raising ("raise to",
  ACPC convention). Opening bets on later streets are raises too.
- Minimum raise increment = the previous bet/raise increment on this street (at least the big blind).
  An all-in for less than a minimum raise is always allowed.
- CALL means check when nothing is owed.
"""


FOLD, CALL, RAISE = 0, 1, 2
ACTION_NAMES = ("fold", "call", "raise")
PREFLOP, FLOP, TURN, RIVER, SHOWDOWN = 0, 1, 2, 3, 4
STREET_NAMES = ("preflop", "flop", "turn", "river", "showdown")
BOARD_CARDS = (0, 3, 4, 5, 5)


class IllegalAction(ValueError):
    pass


@dataclass(frozen=True)
class GameConfig:
    small_blind: int = 50
    big_blind: int = 100
    stack: int = 20000
    ante: int = 0           # (kit) dead money each player posts before the blinds

    @property
    def stack_bb(self) -> float:
        return self.stack / self.big_blind


class Action(NamedTuple):
    kind: int
    amount: int = 0   # RAISE only: total contribution for the hand after the raise

    def __repr__(self) -> str:
        if self.kind == RAISE:
            return f"raise_to({self.amount})"
        return ACTION_NAMES[self.kind]


class HandState:
    """Mutable state of one hand. history entries: (street, seat, kind, contribution_after)."""

    __slots__ = ("cfg", "button", "street", "contrib", "street_start", "to_act", "last_inc", "acted",
                 "folded", "finished", "num_raises", "history")

    def __init__(self, cfg: GameConfig, button: int = 0):
        self.cfg = cfg
        self.button = button
        ante = min(cfg.ante, cfg.stack)                 # (kit) antes count as committed chips
        self.contrib = [ante, ante]
        self.contrib[button] = ante + min(cfg.small_blind, cfg.stack - ante)
        self.contrib[1 - button] = ante + min(cfg.big_blind, cfg.stack - ante)
        self.street = PREFLOP
        self.street_start = [0, 0]
        self.to_act = button
        self.last_inc = cfg.big_blind
        self.acted = [False, False]
        self.folded = -1
        self.finished = False
        self.num_raises = 0       # bets/raises made on the current street (blinds excluded)
        self.history = []

    def copy(self) -> "HandState":
        s = HandState.__new__(HandState)
        s.cfg = self.cfg
        s.button = self.button
        s.street = self.street
        s.contrib = self.contrib[:]
        s.street_start = self.street_start[:]
        s.to_act = self.to_act
        s.last_inc = self.last_inc
        s.acted = self.acted[:]
        s.folded = self.folded
        s.finished = self.finished
        s.num_raises = self.num_raises
        s.history = self.history[:]
        return s

    # -- queries ---------------------------------------------------------------------------
    @property
    def pot(self) -> int:
        return self.contrib[0] + self.contrib[1]

    def stack_left(self, seat: int) -> int:
        return self.cfg.stack - self.contrib[seat]

    def street_bet(self, seat: int) -> int:
        return self.contrib[seat] - self.street_start[seat]

    def to_call(self) -> int:
        return max(0, self.contrib[1 - self.to_act] - self.contrib[self.to_act])

    def call_amount(self) -> int:
        return min(self.to_call(), self.stack_left(self.to_act))

    def can_fold(self) -> bool:
        return not self.finished and self.to_call() > 0

    def raise_bounds(self) -> Optional[Tuple[int, int]]:
        """(min_to, max_to) for a raise by the player to act, or None if raising is not allowed."""
        if self.finished:
            return None
        me, opp = self.to_act, 1 - self.to_act
        max_to = self.cfg.stack
        if self.stack_left(opp) == 0 or max_to <= self.contrib[opp]:
            return None
        min_to = self.contrib[opp] + max(self.last_inc, self.cfg.big_blind)
        return min(min_to, max_to), max_to

    def raise_to_for_fraction(self, frac: float) -> int:
        """Raise-to amount for a bet of `frac` x pot (pot measured after calling), unclamped."""
        me, opp = self.to_act, 1 - self.to_act
        to_call = self.contrib[opp] - self.contrib[me]
        return int(round(self.contrib[opp] + frac * (self.pot + to_call)))

    def clamp_raise(self, amount: int) -> int:
        lo, hi = self.raise_bounds()
        return max(lo, min(hi, int(amount)))

    def is_legal(self, a: Action) -> bool:
        if self.finished:
            return False
        if a.kind == FOLD:
            return self.can_fold()
        if a.kind == CALL:
            return True
        if a.kind == RAISE:
            b = self.raise_bounds()
            return b is not None and b[0] <= a.amount <= b[1]
        return False

    # -- transitions -----------------------------------------------------------------------
    def apply(self, a: Action) -> None:
        if self.finished:
            raise IllegalAction("hand is over")
        me, opp = self.to_act, 1 - self.to_act
        if a.kind == FOLD:
            if not self.can_fold():
                raise IllegalAction("fold when checking is free")
            self.history.append((self.street, me, FOLD, self.contrib[me]))
            self.folded = me
            self.finished = True
            return
        if a.kind == CALL:
            self.contrib[me] += self.call_amount()
            self.acted[me] = True
            self.history.append((self.street, me, CALL, self.contrib[me]))
            if self.contrib[me] < self.contrib[opp]:          # all-in call for less (unequal stacks)
                self._end_street()
            elif self.acted[opp]:
                self._end_street()
            else:
                self.to_act = opp
            return
        if a.kind == RAISE:
            bounds = self.raise_bounds()
            if bounds is None:
                raise IllegalAction("raising not allowed")
            to = int(a.amount)
            if not bounds[0] <= to <= bounds[1]:
                raise IllegalAction(f"raise to {to} outside [{bounds[0]}, {bounds[1]}]")
            self.last_inc = max(self.last_inc, to - self.contrib[opp])
            self.contrib[me] = to
            self.acted[me] = True
            self.acted[opp] = False
            self.num_raises += 1
            self.history.append((self.street, me, RAISE, to))
            self.to_act = opp
            return
        raise IllegalAction(f"unknown action kind {a.kind}")

    def _end_street(self) -> None:
        if self.street == RIVER or self.stack_left(0) == 0 or self.stack_left(1) == 0:
            self.street = SHOWDOWN
            self.finished = True
            return
        self.street += 1
        self.street_start = self.contrib[:]
        self.acted = [False, False]
        self.last_inc = self.cfg.big_blind
        self.num_raises = 0
        self.to_act = 1 - self.button

    # -- results ---------------------------------------------------------------------------
    def payoffs(self, rank0: int = 0, rank1: int = 0) -> Tuple[int, int]:
        """Net chips won by seat 0 and seat 1. Ranks (higher wins) are only used at showdown."""
        if not self.finished:
            raise ValueError("hand not finished")
        if self.folded >= 0:
            amt = self.contrib[self.folded]
            return (-amt, amt) if self.folded == 0 else (amt, -amt)
        matched = min(self.contrib)
        if rank0 > rank1:
            return matched, -matched
        if rank1 > rank0:
            return -matched, matched
        return 0, 0

    def last_betting_street(self) -> int:
        """Street on which the last action happened (to detect all-ins before the river)."""
        return self.history[-1][0] if self.history else PREFLOP

    def __repr__(self) -> str:
        return (f"HandState(street={STREET_NAMES[self.street]}, contrib={self.contrib}, to_act={self.to_act}, "
                f"finished={self.finished}, folded={self.folded})")


