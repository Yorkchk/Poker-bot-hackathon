"""v0: a rule-based bot (hand-strength thresholds + pot odds).

Purpose: emergency submission, a realistic stand-in for typical rule-based competitors, and the
first regression baseline. Hand strength = equity against a random hand, discounted when the
opponent has shown aggression.
"""




@register("heuristic")
class HeuristicBot(Bot):
    # [first raise, re-raise, further raises] thresholds on effective strength
    PRE_RAISE = (0.50, 0.63, 0.72)
    POST_RAISE = (0.70, 0.84, 0.92)

    def __init__(self, seed: int = 0, bluff: float = 0.07, aggro_penalty: float = 0.06, margin: float = 0.03,
                 runouts: int = 120):
        self.rng = np.random.default_rng(seed)
        self.bluff = bluff
        self.aggro_penalty = aggro_penalty
        self.margin = margin
        self.runouts = runouts
        self.tables = get_tables()
        self.pre = PreflopTables()

    def new_match(self, cfg, seed):
        self.rng = np.random.default_rng(seed)

    def strength(self, obs: Observation) -> float:
        if obs.street == PREFLOP:
            return self.pre.vs_random(obs.hole)
        return equity_vs_range(self.tables, obs.hole, obs.board, None, max_runouts=self.runouts, rng=self.rng)

    def act(self, obs: Observation) -> Action:
        s = self.strength(obs)
        opp_raises = sum(1 for (st, seat, kind, _) in obs.history if seat == obs.opp and kind == RAISE)
        street_raises = sum(1 for (st, seat, kind, _) in obs.history if st == obs.street and kind == RAISE)
        eff = s - self.aggro_penalty * opp_raises * (0.5 if obs.street == PREFLOP else 1.0)
        thresholds = self.PRE_RAISE if obs.street == PREFLOP else self.POST_RAISE
        need = thresholds[min(street_raises, 2)]
        to_call = obs.to_call
        odds = to_call / (obs.pot + to_call) if to_call > 0 else 0.0

        if obs.can_raise and eff >= need:
            return Action(RAISE, self._size(obs, eff, street_raises))
        if to_call == 0:
            if obs.can_raise and obs.street > PREFLOP and self.rng.random() < self.bluff:
                return Action(RAISE, obs.raise_to_for_fraction(0.6))
            return Action(CALL)
        if eff >= odds + self.margin:
            return Action(CALL)
        return Action(FOLD)

    def _size(self, obs: Observation, eff: float, street_raises: int) -> int:
        bb = obs.cfg.big_blind
        if obs.street == PREFLOP:
            if street_raises == 0:
                target = int(2.5 * bb) if obs.is_button else int(3.5 * bb)
                if obs.contrib[obs.opp] > bb:      # facing a limp raise / open as BB
                    target = 3 * obs.contrib[obs.opp]
                return max(obs.min_raise_to, min(obs.max_raise_to, target))
            if street_raises >= 3 or eff >= 0.80:
                return obs.max_raise_to
            return max(obs.min_raise_to, min(obs.max_raise_to, 3 * obs.contrib[obs.opp]))
        frac = 0.66 if eff < 0.85 else 1.0
        amt = obs.raise_to_for_fraction(frac)
        # commit when the raise would leave little behind
        if obs.max_raise_to - amt < 0.3 * (obs.pot + amt):
            return obs.max_raise_to
        return amt


