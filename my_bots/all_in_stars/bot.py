# Model of a hand: heads-up, both players at the hand's effective stack (the bigger stack's excess can
# never be won or lost), the button is seat 0 of the model, antes are chips both players committed
# before the blinds (so pot odds include them). Contributions are "total chips committed this hand";
# the kit's raise amounts are "total on this street", converted with the street's starting point.
# The history is replayed from action_log at every decision, so it is always exactly the real one.

AGENT_CONFIG = {'blueprint': 'bp_cloud', 'exploit': True, 'river': True, 'river_time': 0.8, 'river_iters': 200, 'exploit_min_obs': 12}

STREET_OF = {"preflop": PREFLOP, "flop": FLOP, "turn": TURN, "river": RIVER}
BET_ACTIONS = frozenset(("fold", "check", "call", "raise", "all_in"))


class SyncError(RuntimeError):
    pass


def _cards(xs) -> list:
    return [parse_card(c) for c in (xs or [])]


def _invested(entries) -> dict:
    """Chips each table seat has put in this hand (antes, blinds, bets), from action_log entries."""
    invested = defaultdict(int)
    street_bet = defaultdict(int)
    street = None
    for e in entries:
        if e.get("street") != street:
            street = e.get("street")
            street_bet = defaultdict(int)
        act, seat, amt = e.get("action"), e.get("seat"), int(e.get("amount") or 0)
        if act == "ante":
            invested[seat] += amt
        elif act in ("small_blind", "big_blind", "call"):
            invested[seat] += amt
            street_bet[seat] += amt
        elif act in ("raise", "all_in"):                 # amount = the bettor's total on the street
            invested[seat] += max(0, amt - street_bet[seat])
            street_bet[seat] = max(street_bet[seat], amt)
    return invested


def _model_action(s: HandState, role: int, act: str, amount: int, ante: int) -> Action:
    if act == "fold":
        if not s.can_fold():
            raise SyncError("fold when checking was free")
        return Action(FOLD)
    if act in ("check", "call"):
        return Action(CALL)
    base = s.street_start[role] if s.street > PREFLOP else ante
    to = base + amount
    rb = s.raise_bounds()
    if rb is None or to <= s.contrib[1 - role]:
        return Action(CALL)                               # an all-in that does not raise
    return Action(RAISE, max(rb[0], min(rb[1], to)))       # beyond the effective stack = all-in


def _replay(cfg: GameConfig, entries, button_seat, ante: int, partial: bool = False) -> HandState:
    """Model state after the betting actions in `entries`. partial=True stops quietly at the first
    action the model cannot represent (used for finished hands) instead of raising SyncError."""
    s = HandState(cfg, 0)
    for e in entries:
        act = e.get("action")
        if act not in BET_ACTIONS:
            continue
        try:
            if s.finished:
                raise SyncError("action after the end of the hand")
            role = 0 if e.get("seat") == button_seat else 1
            if role != s.to_act:
                raise SyncError(f"seat {e.get('seat')} acted out of turn")
            st = STREET_OF.get(e.get("street"))
            if st is not None and st != s.street:
                raise SyncError(f"{e.get('street')} action while the model is on {STREET_NAMES[s.street]}")
            s.apply(_model_action(s, role, act, int(e.get("amount") or 0), ante))
        except (SyncError, IllegalAction):
            if partial:
                break
            raise
    return s


def _opp_preflop_events(cfg: GameConfig, entries, button_seat, ante: int, opp_role: int) -> list:
    """[(situation, flag)] for the opponent's preflop decisions in a finished hand:
    ("first", shoved) with no raise yet, ("facing_raise", shoved) facing our raise,
    ("facing_shove", called) facing our all-in."""
    out = []
    s = HandState(cfg, 0)
    for e in entries:
        act = e.get("action")
        if act not in BET_ACTIONS:
            continue
        if s.finished or s.street != PREFLOP:
            break
        role = 0 if e.get("seat") == button_seat else 1
        try:
            a = _model_action(s, role, act, int(e.get("amount") or 0), ante)
        except SyncError:
            break
        if role == opp_role and role == s.to_act:
            shove = a.kind == RAISE and (a.amount >= cfg.stack or act == "all_in")
            if s.to_call() > 0 and s.stack_left(1 - opp_role) == 0:
                out.append(("facing_shove", a.kind != FOLD))
            elif s.num_raises == 0:
                out.append(("first", shove))
            elif s.to_call() > 0:
                out.append(("facing_raise", shove))
        try:
            s.apply(a)
        except IllegalAction:
            break
    return out


class ShortStack:
    """(kit) Preflop decisions that end the betting: call or fold facing an all-in, and shove or fold as
    the small blind when stacks are short (or against an opponent that re-shoves our opens).

    The blueprint was trained 200bb deep and maps every real all-in onto its abstract 200bb all-in, so it
    calls only with premium hands even at 15bb or against a bot that shoves every hand. Here the
    opponent's shove/call ranges are the top-f hands by all-in equity, with f estimated from what it did
    so far in the match (Beta prior = heads-up push/fold Nash frequencies at this stack depth), and we
    play the best response. Deep, a risk margin on equity keeps us from flipping for the match with a
    thin edge against an opponent we out-play anyway."""

    PUSH_FOLD_BB = 13.0        # shove-or-fold as the small blind at or below this effective stack
    PRIOR_STRENGTH = 4.0       # pseudo-observations of the Nash prior
    MAX_MARGIN = 0.10          # equity margin at >= 100bb, none at <= 20bb

    def __init__(self, pre: PreflopTables, path: Path):
        nash = json.loads(Path(path).read_text())
        self.grid_s = np.asarray(nash["stack_bb"], dtype=np.float64)
        self.grid_a = np.asarray(nash["ante_bb"], dtype=np.float64)
        self.push_freq = np.asarray(nash["push_freq"], dtype=np.float64)   # [ante, stack]
        self.call_freq = np.asarray(nash["call_freq"], dtype=np.float64)
        self.pre = pre
        combos = np.bincount(PREFLOP_CLASS, minlength=169).astype(np.float64)
        self.order = np.argsort(-pre.vs_random_class, kind="stable")
        self.ord_combos = combos[self.order]
        self.ord_before = np.cumsum(self.ord_combos) - self.ord_combos
        self.n = defaultdict(float)
        self.k = defaultdict(float)

    @staticmethod
    def band(stack_bb: float) -> str:
        return "short" if stack_bb <= 25 else "deep"

    def prior(self, situation: str, stack_bb: float, ante_bb: float) -> float:
        i = int(np.abs(self.grid_a - ante_bb).argmin())
        push = float(np.interp(stack_bb, self.grid_s, self.push_freq[i]))
        call = float(np.interp(stack_bb, self.grid_s, self.call_freq[i]))
        return push if situation == "first" else (0.7 * call if situation == "facing_raise" else call)

    def freq(self, situation: str, stack_bb: float, ante_bb: float) -> float:
        key = (situation, self.band(stack_bb))
        p = self.prior(situation, stack_bb, ante_bb)
        return (self.k[key] + self.PRIOR_STRENGTH * p) / (self.n[key] + self.PRIOR_STRENGTH)

    def observe(self, cfg: GameConfig, events) -> None:
        b = self.band(cfg.stack / cfg.big_blind)
        for situation, flag in events:
            self.n[(situation, b)] += 1.0
            self.k[(situation, b)] += float(flag)

    def top_range(self, frac: float) -> np.ndarray:
        """float[1326]: the top `frac` of all combos by all-in equity vs a random hand."""
        total = 1326.0 * min(1.0, max(0.005, frac))
        take = np.clip(total - self.ord_before, 0.0, self.ord_combos)
        w = np.zeros(169)
        w[self.order] = take / self.ord_combos
        return w[PREFLOP_CLASS]

    def margin(self, stack_bb: float) -> float:
        return self.MAX_MARGIN * min(1.0, max(0.0, (stack_bb - 20.0) / 80.0))

    def act(self, s: HandState, role: int, hole) -> Optional[Action]:
        if s.street != PREFLOP or s.finished or s.to_act != role:
            return None
        cfg = s.cfg
        S, a = cfg.stack / cfg.big_blind, cfg.ante / cfg.big_blind
        me, opp = role, 1 - role
        call = s.call_amount()
        if s.to_call() > 0 and (s.stack_left(opp) == 0 or call >= s.stack_left(me)):
            if s.num_raises == 0:
                frac = 1.0                       # all-in from posting the blind: any two cards
            else:
                frac = self.freq("first" if s.num_raises == 1 else "facing_raise", S, a)
            eq = self.pre.vs_range(hole, self.top_range(frac))
            need = call / max(s.pot + call, 1) + self.margin(S)
            return Action(CALL) if eq >= need else Action(FOLD)
        if role == 0 and s.num_raises == 0 and s.contrib[me] < s.contrib[opp] and s.raise_bounds():
            b = self.band(S)
            reshover = self.n[("facing_raise", b)] >= 5 and self.freq("facing_raise", S, a) >= 0.5
            if S <= self.PUSH_FOLD_BB or reshover:
                c = self.freq("facing_shove", S, a)
                e = self.pre.vs_range(hole, self.top_range(c))
                m, stack = s.contrib[me], cfg.stack
                ev_push = (1.0 - c) * s.pot + c * (2.0 * e * stack - (stack - m)) - c * self.margin(S) * 2.0 * stack
                return Action(RAISE, s.raise_bounds()[1]) if ev_push > 0 else Action(FOLD)
        return None


class KitOpponentModel(OpponentModel):
    """(kit) Same model, style flags after fewer observations: a freezeout against a calling station
    lasts ~12 hands, too short for the original thresholds (25 bets faced, 12 showdowns)."""

    def flags(self) -> set:
        out = set()
        fold_rate, _, n_facing = self.facing_bet_rates()
        if n_facing >= 10 and fold_rate <= 0.06:
            out.add("station")
        if n_facing >= 10 and fold_rate >= 0.80:
            out.add("folder")
        tot = self.total.sum()
        if tot >= 20 and self.total[A_RAISE] / tot >= 0.40 and self.uninformative(0.5, 6):
            out.add("maniac")
        corr = self.strength_aggression_corr()
        if (corr is not None and corr < 0.08 and len(self._sd_strength) >= 15 and tot >= 30
                and self.total[A_RAISE] / tot >= 0.25 and self.uninformative(0.5, 12)):
            out.add("random")
        return out


class _Hand:
    __slots__ = ("hand_id", "hand_num", "me", "opp", "me_id", "opp_id", "button", "role", "cfg", "ante",
                 "hole", "board", "ok", "why", "reported")

    def __init__(self, **kw):
        self.board, self.ok, self.why, self.reported = [], True, "", False
        for k, v in kw.items():
            setattr(self, k, v)


class RawPlayer:
    """Plays from game_state alone (equity vs a random hand + pot odds). Used when the history cannot
    be modelled (e.g. hand-made states without blind posts, more than two players)."""

    def __init__(self, tables: Tables, pre: PreflopTables, seed: int):
        self.tables, self.pre = tables, pre
        self.rng = np.random.default_rng(seed)

    def act(self, gs: dict) -> dict:
        try:
            hole, board = _cards(gs.get("your_cards")), _cards(gs.get("community_cards"))
            pot, owed = int(gs.get("pot") or 0), int(gs.get("amount_owed") or 0)
            stack, bet = int(gs.get("your_stack") or 0), int(gs.get("your_bet_this_street") or 0)
            can_check = bool(gs.get("can_check"))
            if len(hole) != 2:
                raise ValueError("no hole cards")
            s = equity_vs_range(self.tables, hole, board, None, max_runouts=150, rng=self.rng) if board \
                else self.pre.vs_random(hole)
            odds = owed / (pot + owed) if owed > 0 else 0.0
            if stack > owed and s >= (0.62 if not board else 0.80):
                target = max(int(gs.get("min_raise_to") or 0), int(gs.get("current_bet") or 0) + int(0.75 * (pot + owed)))
                return {"action": "all_in"} if target >= stack + bet else {"action": "raise", "amount": target}
            if can_check:
                return {"action": "check"}
            return {"action": "call"} if s >= odds + 0.03 else {"action": "fold"}
        except Exception:
            return {"action": "check"} if gs.get("can_check") else {"action": "fold"}


class KitBot:
    def __init__(self, seed: int):
        self.agent = Agent(seed=seed, **AGENT_CONFIG)
        self.raw = RawPlayer(self.agent.tables, self.agent.fallback.pre, seed + 7)
        self.short = ShortStack(self.agent.fallback.pre, tables_dir() / "pushfold.json")
        self.agent.model = KitOpponentModel()
        self.hand: Optional[_Hand] = None
        self.reported = set()              # hand numbers the agent has seen end (decided or observed)
        self.last_hand_num = -1
        self.stats = defaultdict(int)

    # -- the kit's entry point ---------------------------------------------------------------
    def decide(self, gs: dict) -> dict:
        if gs.get("type") == "warmup":
            return {"action": "check"}
        try:
            return self._decide(gs)
        except Exception as e:                   # never crash: play from the raw state instead
            self.stats["raw"] += 1
            if self.hand is not None and self.hand.hand_id == gs.get("hand_id"):
                self.hand.ok, self.hand.why = False, f"{type(e).__name__}: {e}"[:160]
            out = self.raw.act(gs)
            out["debug"] = {"src": "raw", "why": f"{type(e).__name__}: {e}"[:160]}
            return out

    def _decide(self, gs: dict) -> dict:
        if len(gs.get("players") or []) != 2:
            raise SyncError("not heads-up")
        if self.hand is None or self.hand.hand_id != gs.get("hand_id"):
            self._start_hand(gs)
        h = self.hand
        if not h.ok:
            raise SyncError(h.why or "hand out of sync")
        s = _replay(h.cfg, gs.get("action_log") or [], h.button, h.ante)
        street = STREET_OF.get(gs.get("street"))
        if s.finished or s.to_act != h.role or s.street != street:
            raise SyncError("the model does not expect a decision here")
        owed, stack = int(gs.get("amount_owed") or 0), int(gs.get("your_stack") or 0)
        if s.call_amount() != min(owed, stack):
            raise SyncError(f"call amount {s.call_amount()} in the model, {min(owed, stack)} at the table")
        h.board = _cards(gs.get("community_cards"))
        obs = observe(s, h.role, h.hole, h.board, h.hand_num)
        self.agent.timebank.per_decision_limit = float(gs.get("time_limit_ms") or 2000) / 1000.0
        a = self.short.act(s, h.role, h.hole)
        if a is not None:                     # ends our betting in this hand: the agent need not track it
            a, src = Agent._legalise(obs, a), "shortstack"
        else:
            before = dict(self.agent.stats)
            a = self.agent.act(obs)
            src = next((k for k in ("errors", "fallback", "exploit", "river_solves")
                        if self.agent.stats[k] > before[k]), "blueprint")
            if a.kind == RAISE and s.street < RIVER:
                a = self._snap(a, s, h.role)
            elif a.kind == RAISE and s.street == RIVER:
                b = self._river_filter(a, s, h)
                if b.kind != a.kind:
                    self._repoint_pending(b.kind, obs)
                    a, src = b, src + "+filter"
        self.stats[src] += 1
        out = self._to_kit(a, s, h, gs)
        out["debug"] = {"src": src, "eff_bb": round(h.cfg.stack / h.cfg.big_blind, 1)}
        return out

    def _river_filter(self, a: Action, s: HandState, h: _Hand) -> Action:
        """(kit) The river solver plays against the range the blueprint attributes to the opponent, which
        bluffs at equilibrium frequencies; most bots bet for value and call with any decent hand. So,
        unless the opponent's aggression is flagged as uninformative: raise a river bet only with a
        strong hand (exact EHS vs a random hand >= 0.9), and bluff into a check only when the opponent's
        observed fold rate for that bet size makes the bluff profitable."""
        model = self.agent.model
        if model.flags() & {"maniac", "random"}:
            return a
        ehs = float(np.nan_to_num(river_strengths(self.agent.tables, h.board)[combo_index(*h.hole)], nan=0.5))
        if s.to_call() > 0:
            if ehs >= 0.90:
                return a
            return Action(CALL) if ehs >= 0.5 or not s.can_fold() else Action(FOLD)
        if ehs >= 0.5:
            return a
        bet = a.amount - s.contrib[h.role]
        fp = model.fold_prob(RIVER, size_class(bet, s.pot, a.amount >= s.cfg.stack))
        return Action(CALL) if fp * s.pot - (1.0 - fp) * bet < 0 else a

    def _repoint_pending(self, kind: int, obs: Observation) -> None:
        """Keep the agent's range tracking on the action actually played."""
        ag, p = self.agent, self.agent.pending
        try:
            if p and p["kind"] == "solver" and ag.solver is not None:
                i = next(i for i, x in enumerate(ag.solver.actions(0)) if x.kind == kind)
                ag.pending = {"kind": "solver", "idx": i, "vec": ag.solver.range_update(0, i)}
            elif p and p["kind"] == "bp":
                i, _ = ag.bp.find_child(ag.node, kind)
                if i is not None:
                    ag.pending = {"kind": "bp", "idx": i, "vec": ag._bp_factor(ag.node, obs, [(i, 1.0)])}
        except StopIteration:
            pass

    @staticmethod
    def _snap(a: Action, s: HandState, role: int) -> Action:
        """A blueprint raise that would commit most of a (real, shallower) stack becomes all-in, as the
        abstraction itself does at 200bb (allin_snap = 0.6)."""
        rb = s.raise_bounds()
        if rb is not None and a.amount < rb[1] and a.amount - s.contrib[role] >= 0.6 * s.stack_left(role):
            return Action(RAISE, rb[1])
        return a

    @staticmethod
    def _to_kit(a: Action, s: HandState, h: _Hand, gs: dict) -> dict:
        can_check = bool(gs.get("can_check"))
        if a.kind == RAISE and s.raise_bounds() is not None:
            base = s.street_start[h.role] if s.street > PREFLOP else h.ante
            total = int(a.amount) - base                     # the kit's amount: total on this street
            cap = int(gs.get("your_stack") or 0) + int(gs.get("your_bet_this_street") or 0)
            total = max(total, int(gs.get("min_raise_to") or 0))
            if int(a.amount) >= s.cfg.stack or total >= cap:
                return {"action": "all_in"}
            return {"action": "raise", "amount": total}
        if a.kind == FOLD and not can_check:
            return {"action": "fold"}
        return {"action": "check"} if can_check else {"action": "call"}

    # -- hand lifecycle ------------------------------------------------------------------------
    def _start_hand(self, gs: dict) -> None:
        mal = gs.get("match_action_log") or []
        hn = int(gs.get("hand_num") or 0)
        if self.hand is not None and not self.hand.reported:
            self._finish_hand(self.hand, mal)
        me = gs["seat_to_act"]
        opp_p = next(p for p in gs["players"] if p["seat"] != me)
        me_id, opp_id = gs.get("your_bot_id"), opp_p.get("bot_id")
        self._observe_skipped(mal, hn, me_id, opp_id)
        invested = _invested(gs.get("action_log") or [])
        stacks = {p["seat"]: int(p["stack"]) + invested[p["seat"]] for p in gs["players"]}
        blinds = gs.get("blinds") or {}
        sb, bb = int(blinds.get("sb") or 0), int(blinds.get("bb") or 0)
        ante = int(blinds.get("ante") or 0)
        eff = min(stacks[me], stacks[opp_p["seat"]])
        cfg = GameConfig(sb, bb, eff, ante)
        button = gs.get("button_seat")
        role = 0 if me == button else 1
        self.hand = _Hand(hand_id=gs.get("hand_id"), hand_num=hn, me=me, opp=opp_p["seat"], me_id=me_id,
                          opp_id=opp_id, button=button, role=role, cfg=cfg, ante=min(ante, eff),
                          hole=tuple(_cards(gs.get("your_cards"))))
        self.last_hand_num = max(self.last_hand_num, hn)
        if not (0 < sb <= bb) or eff <= 0 or len(self.hand.hole) != 2:
            self.hand.ok, self.hand.why = False, "unusual blinds/stacks/cards"
            return
        self.agent.cfg = cfg
        self.agent.new_hand(hn, role, 0, self.hand.hole)

    def _finish_hand(self, h: _Hand, mal) -> None:
        """Report a hand we played to the agent (its last actions and any showdown)."""
        h.reported = True
        self.reported.add(h.hand_num)
        entries = [e for e in mal if e.get("hand_num") == h.hand_num]
        try:
            self.short.observe(h.cfg, _opp_preflop_events(h.cfg, entries, h.button, h.ante, 1 - h.role))
        except Exception:
            self.stats["observe_errors"] += 1
        if not h.ok:
            return
        try:
            s = _replay(h.cfg, entries, h.button, h.ante, partial=True)
            opp = next((_cards(e.get("cards")) for e in entries
                        if e.get("action") == "show" and e.get("bot_id") == h.opp_id), None)
            self.agent.end_hand(HandResult(h.hand_num, h.role, 0, 0, tuple(h.board), h.hole,
                                           tuple(opp) if opp and len(opp) == 2 else None, tuple(s.history),
                                           tuple(s.contrib), bool(opp)))
        except Exception:
            self.stats["observe_errors"] += 1

    def _observe_skipped(self, mal, current: int, me_id, opp_id) -> None:
        """Hands we never had to act in (e.g. the opponent folded its small blind) still teach the
        opponent model; replay them from match_action_log."""
        by_hand = defaultdict(list)
        for e in mal:
            n = e.get("hand_num")
            if isinstance(n, int) and self.last_hand_num < n < current and n not in self.reported:
                by_hand[n].append(e)
        for n in sorted(by_hand):
            entries = by_hand[n]
            self.reported.add(n)
            if not any(e.get("action") in BET_ACTIONS for e in entries):
                continue                                     # all-in from the posts: no decisions
            try:
                post = {e.get("action"): e for e in entries if e.get("action") in ("small_blind", "big_blind", "ante")}
                button = post["small_blind"]["seat"]               # heads-up: the button posts the small blind
                me_seat = next(e["seat"] for e in entries if e.get("bot_id") == me_id)
                role = 0 if me_seat == button else 1
                sb, bb = int(post["small_blind"]["amount"]), int(post["big_blind"]["amount"])
                ante = int(post["ante"]["amount"]) if "ante" in post else 0
                stack = max(100 * bb, self.hand.cfg.stack if self.hand is not None else 0)
                cfg = GameConfig(sb, bb, stack, ante)
                self.short.observe(cfg, _opp_preflop_events(cfg, entries, button, min(ante, stack), 1 - role))
                shown = {e.get("bot_id"): _cards(e.get("cards")) for e in entries if e.get("action") == "show"}
                used = set(c for cs in shown.values() for c in cs)
                hole = tuple(shown.get(me_id) or [c for c in range(52) if c not in used][:2])
                self.agent.cfg = cfg
                self.agent.new_hand(n, role, 0, hole)
                s = _replay(cfg, entries, button, min(ante, stack), partial=True)
                opp = shown.get(opp_id)
                self.agent.end_hand(HandResult(n, role, 0, 0, (), hole, tuple(opp) if opp else None,
                                               tuple(s.history), tuple(s.contrib), bool(opp)))
                self.stats["observed_hands"] += 1
            except Exception:
                self.stats["observe_errors"] += 1


