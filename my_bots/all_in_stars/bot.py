"""Model-based exploitation: LBR-style EV of candidate actions against the opponent model.

EV (relative to folding now), with pot = chips in the pot and c = our amount to call:
    check/call : eq * (pot + c) - c                        (showdown approximation)
    raise to X : fp * pot + (1 - fp) * (eq_c * (pot + 2d - c) - d),   d = X - our contribution
where eq is our equity against the opponent's (model-weighted) range, fp the modelled fold
probability for that bet-size class, and eq_c our equity against the continuing range (the
opponent folds its weakest hands first). The agent only deviates from its near-equilibrium action
when the best EV beats the equilibrium mix by a street-dependent margin (the approximation ignores
future betting, so early streets need a larger edge).
"""





MARGIN = {0: 0.15, 1: 0.10, 2: 0.07, 3: 0.04}     # fraction of the pot, by street


def remove_weakest(weights: np.ndarray, strength: np.ndarray, mass: float) -> np.ndarray:
    """Drop `mass` (fraction of total weight) from the weakest combos (partial at the boundary)."""
    w = weights.copy()
    tot = w.sum()
    if tot <= 0 or mass <= 0:
        return w
    if mass >= 1:
        return np.zeros_like(w)
    order = np.argsort(strength, kind="stable")
    cum = np.cumsum(w[order]) / tot
    cut = np.searchsorted(cum, mass)
    w[order[:cut]] = 0.0
    if cut < order.size:
        prev = cum[cut - 1] if cut > 0 else 0.0
        frac_removed = (mass - prev) * tot / max(w[order[cut]], 1e-300)
        w[order[cut]] *= max(0.0, 1.0 - frac_removed)
    return w


class Exploiter:
    def __init__(self, tables, buckets: Buckets, pre: PreflopTables, runouts: int = 80, seed: int = 0):
        self.tables = tables
        self.buckets = buckets
        self.pre = pre
        self.runouts = runouts
        self.rng = np.random.default_rng(seed)

    def opp_strength(self, obs: Observation) -> np.ndarray:
        if obs.street == PREFLOP:
            return self.pre.vs_random_class[PREFLOP_CLASS].astype(np.float64)
        if obs.street == RIVER:
            s = river_strengths(self.tables, obs.board)
            return np.nan_to_num(s, nan=0.0)
        b = self.buckets.all(obs.street, obs.board).astype(np.float64)
        b[b == 65535] = 0.0
        return b

    def model_range(self, obs: Observation, tracked: np.ndarray, lam: float) -> np.ndarray:
        valid = ((COMBO_MASK & np.uint64(cards_mask(list(obs.hole) + list(obs.board)))) == 0).astype(np.float64)
        t = np.asarray(tracked, dtype=np.float64) * valid
        u = valid / valid.sum()
        if t.sum() <= 0:
            return u
        return lam * t / t.sum() + (1.0 - lam) * u

    def evaluate(self, obs: Observation, tracked: np.ndarray, model: OpponentModel,
                 candidates: List[Action]) -> Dict[Action, float]:
        r = self.model_range(obs, tracked, model.range_lambda())
        strength = self.opp_strength(obs)
        pot, c = obs.pot, obs.to_call
        me = obs.seat
        rows = [r]
        meta: List[Tuple[Action, float]] = []
        for a in candidates:
            if a.kind != RAISE:
                continue
            d = a.amount - obs.contrib[me]
            cls = size_class(d - c, pot + c, a.amount >= obs.cfg.stack)
            fp = model.fold_prob(obs.street, cls)
            meta.append((a, fp))
            rows.append(remove_weakest(r, strength, fp))
        eqs = self._equities(obs, np.array(rows))
        out: Dict[Action, float] = {}
        for a in candidates:
            if a.kind == FOLD:
                out[a] = 0.0
            elif a.kind == CALL:
                out[a] = eqs[0] * (pot + c) - c
        for k, (a, fp) in enumerate(meta):
            d = a.amount - obs.contrib[me]
            out[a] = fp * pot + (1.0 - fp) * (eqs[k + 1] * (pot + 2 * d - c) - d)
        return out

    def _equities(self, obs: Observation, rows: np.ndarray) -> np.ndarray:
        if obs.street == PREFLOP:
            return np.array([self.pre.vs_range(obs.hole, w) for w in rows])
        return equity_multi(self.tables, obs.hole, obs.board, rows, self.runouts, self.rng)


def candidate_raises(obs: Observation, fractions=(0.5, 1.0)) -> List[Action]:
    if not obs.can_raise:
        return []
    amts = {obs.raise_to_for_fraction(f) for f in fractions} | {obs.max_raise_to}
    return [Action(RAISE, a) for a in sorted(amts)]


