@dataclass(frozen=True)
class Observation:
    cfg: GameConfig
    hand_no: int
    seat: int
    button: int
    hole: Tuple[int, int]
    board: Tuple[int, ...]           # visible board cards
    street: int
    contrib: Tuple[int, int]         # total chips committed this hand, by seat
    street_start: Tuple[int, int]    # contributions at the start of the current street
    can_fold: bool
    call_amount: int
    min_raise_to: Optional[int]      # None if raising is not allowed
    max_raise_to: Optional[int]
    history: Tuple[tuple, ...]       # (street, seat, kind, contribution_after)
    time_left: Optional[float] = None   # seconds left on the match clock, if the engine says
    hands_left: Optional[int] = None    # hands left in the match, if known

    @property
    def pot(self) -> int:
        return self.contrib[0] + self.contrib[1]

    @property
    def opp(self) -> int:
        return 1 - self.seat

    @property
    def to_call(self) -> int:
        return max(0, self.contrib[self.opp] - self.contrib[self.seat])

    @property
    def is_button(self) -> bool:
        return self.seat == self.button

    @property
    def can_raise(self) -> bool:
        return self.min_raise_to is not None

    def raise_to_for_fraction(self, frac: float) -> int:
        """Legal raise-to for a bet of frac x pot (pot after calling), clamped to [min, max]."""
        to_call = self.contrib[self.opp] - self.contrib[self.seat]
        amt = int(round(self.contrib[self.opp] + frac * (self.pot + to_call)))
        return max(self.min_raise_to, min(self.max_raise_to, amt))

    def passive(self) -> Action:
        return Action(CALL)

    def fold_or_check(self) -> Action:
        return Action(FOLD) if self.can_fold else Action(CALL)


def observe(state: HandState, seat: int, hole, board_full, hand_no: int,
            time_left: Optional[float] = None, hands_left: Optional[int] = None) -> Observation:
    rb = state.raise_bounds()
    return Observation(
        cfg=state.cfg, hand_no=hand_no, seat=seat, button=state.button,
        hole=(int(hole[0]), int(hole[1])),
        board=tuple(int(c) for c in board_full[:BOARD_CARDS[state.street]]),
        street=state.street, contrib=(state.contrib[0], state.contrib[1]),
        street_start=(state.street_start[0], state.street_start[1]),
        can_fold=state.can_fold(), call_amount=state.call_amount(),
        min_raise_to=None if rb is None else rb[0], max_raise_to=None if rb is None else rb[1],
        history=tuple(state.history), time_left=time_left, hands_left=hands_left)


def replay(cfg: GameConfig, button: int, history) -> HandState:
    """Rebuild a HandState from an observation's history (useful inside bots)."""
    s = HandState(cfg, button)
    for _street, _seat, kind, after in history:
        s.apply(Action(kind, after if kind == RAISE else 0))
    return s


