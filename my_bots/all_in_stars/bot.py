# 7-card evaluator, Tables and Buckets (replace core/tables.py and core/buckets.py)
# =================================================================================================
# Vectorised NumPy port of pokerbot.offline.evaluator_nb.eval7: same integer values
#   category << 20 | r1 << 16 | r2 << 12 | r3 << 8 | r4 << 4 | r5
# Dense ranks (0 = weakest) are positions in the sorted list of the 4824 distinct 7-card values, so
# Tables.river_ranks() returns exactly what river_rank.npy held (checked over all 134,459 canonical
# river boards x 1326 combos by tools/build_bot.py --verify).

def _eval_tables():
    highbit = np.full(8192, -1, np.int64)
    popcount = np.zeros(8192, np.int64)
    straight_top = np.full(8192, -1, np.int64)
    top = {n: np.zeros(8192, np.int64) for n in (2, 3, 5)}
    for m in range(8192):
        if m:
            highbit[m] = m.bit_length() - 1
            popcount[m] = bin(m).count("1")
        for hi in range(12, 3, -1):
            need = 0x1F << (hi - 4)
            if m & need == need:
                straight_top[m] = hi
                break
        else:
            if m & 0x100F == 0x100F:          # A-2-3-4-5 ("wheel"), top card is the 5
                straight_top[m] = 3
        for n in top:
            v, mm = 0, m
            for _ in range(n):
                v <<= 4
                if mm:
                    h = mm.bit_length() - 1
                    v |= h
                    mm &= ~(1 << h)
            top[n][m] = v
    return highbit, popcount, straight_top, top


EV_HIGHBIT, EV_POPCOUNT, EV_STRAIGHT_TOP, EV_TOP = _eval_tables()


def _bit_of(r):
    return np.where(r >= 0, np.left_shift(1, np.maximum(r, 0)), 0)


def eval_masks(s0, s1, s2, s3):
    """Hand values of 7-card hands given their per-suit 13-bit rank masks (int64 arrays)."""
    HB, POP, ST, TOP = EV_HIGHBIT, EV_POPCOUNT, EV_STRAIGHT_TOP, EV_TOP
    allm = s0 | s1 | s2 | s3
    fm = np.where(POP[s0] >= 5, s0, np.where(POP[s1] >= 5, s1,
                  np.where(POP[s2] >= 5, s2, np.where(POP[s3] >= 5, s3, 0))))
    quads = s0 & s1 & s2 & s3
    ge3 = (s0 & s1 & s2) | (s0 & s1 & s3) | (s0 & s2 & s3) | (s1 & s2 & s3)
    ge2 = (s0 & s1) | (s0 & s2) | (s0 & s3) | (s1 & s2) | (s1 & s3) | (s2 & s3)
    st = ST[allm]
    t = HB[ge3]
    tb = _bit_of(t)
    rest = ge2 & ~tb
    p1 = HB[ge2]
    p1b = _bit_of(p1)
    rem = ge2 & ~p1b
    p2 = HB[rem]
    p2b = _bit_of(p2)
    q = HB[quads]
    qb = _bit_of(q)
    v = TOP[5][allm]                                                              # high card
    v = np.where(ge2 != 0, np.where(rem != 0,
                 (2 << 20) | (p1 << 16) | (p2 << 12) | (HB[allm & ~p1b & ~p2b] << 8),   # two pair
                 (1 << 20) | (p1 << 16) | (TOP[3][allm & ~p1b] << 4)), v)               # pair
    v = np.where(ge3 != 0, (3 << 20) | (t << 16) | (TOP[2][allm & ~tb] << 8), v)  # trips
    v = np.where(st >= 0, (4 << 20) | (st << 16), v)                             # straight
    v = np.where((ge3 != 0) & (rest != 0), (6 << 20) | (t << 16) | (HB[rest] << 12), v)  # full house
    v = np.where(quads != 0, (7 << 20) | (q << 16) | (HB[allm & ~qb] << 12), v)   # quads
    stf = ST[fm]
    v = np.where(fm != 0, np.where(stf >= 0, (8 << 20) | (stf << 16), (5 << 20) | TOP[5][fm]), v)  # (straight) flush
    return v


def _suit_masks(cards: np.ndarray):
    """Per-suit rank masks of each row of an (N, k) int array of cards -> 4 int64 arrays (N,)."""
    cards = np.asarray(cards, dtype=np.int64)
    bits = np.left_shift(np.int64(1), cards >> 2)
    suits = cards & 3
    return [np.where(suits == k, bits, 0).sum(axis=1) for k in range(4)]   # distinct cards: sum == OR


INVALID_RANK = 65535


class Tables:
    """Same interface as core/tables.py; ranks are evaluated instead of read from river_rank.npy."""

    def __init__(self, root: "str | Path | None" = None):
        d = Path(root) if root is not None else tables_dir()
        self.dir = d
        self.canon_id = {}
        self.perm = {}
        for k, name in ((3, "flop"), (4, "turn")):
            with np.load(d / f"{name}_canon.npz") as z:
                self.canon_id[k] = z["canon_id"]
                self.perm[k] = z["perm"]
        self.rank_values = np.load(d / "rank_values.npy").astype(np.int64)    # 4824 values, ascending
        if self.rank_values.size != 4824:
            raise ValueError("rank_values.npy must hold the 4824 distinct 7-card values")
        cc = COMBO_CARDS.astype(np.int64)
        self._combo_masks = [np.where((cc[:, 0] & 3) == k, np.int64(1) << (cc[:, 0] >> 2), 0) |
                             np.where((cc[:, 1] & 3) == k, np.int64(1) << (cc[:, 1] >> 2), 0) for k in range(4)]
        self._combo_cardmask = COMBO_MASK.astype(np.uint64)

    # -- canonicalisation (flop and turn bucket tables) ------------------------------------
    def canon(self, board) -> tuple:
        """(canonical id, suit-permutation index) of a 3/4-card board."""
        b = sorted(int(c) for c in board)
        k = len(b)
        idx = 0
        for i, c in enumerate(b):
            idx += int(BINOM[c, i + 1])
        return int(self.canon_id[k][idx]), int(self.perm[k][idx])

    # -- ranks -----------------------------------------------------------------------------
    def ranks_many(self, boards: np.ndarray) -> np.ndarray:
        """(R, 1326) uint16 dense rank of every combo on every 5-card board (65535 = blocked)."""
        b = np.atleast_2d(np.asarray(boards, dtype=np.int64))
        bm = _suit_masks(b)
        v = eval_masks(*[bm[k][:, None] | self._combo_masks[k][None, :] for k in range(4)])
        r = np.searchsorted(self.rank_values, v).astype(np.uint16)
        board_mask = np.zeros(b.shape[0], dtype=np.uint64)
        for j in range(b.shape[1]):
            board_mask |= np.left_shift(np.uint64(1), b[:, j].astype(np.uint64))
        r[(self._combo_cardmask[None, :] & board_mask[:, None]) != 0] = INVALID_RANK
        return r

    def river_ranks(self, board) -> np.ndarray:
        """uint16[1326]: rank of every combo on a 5-card board (original suits), 65535 if blocked."""
        key = tuple(sorted(int(c) for c in board))
        if getattr(self, "_rr_key", None) != key:        # buckets, solver and exploiter ask for the same board
            self._rr_key, self._rr = key, self.ranks_many(np.array([key]))[0]
        return self._rr.copy()

    def hand_rank(self, board, hole) -> int:
        return int(self.river_ranks(board)[combo_index(hole[0], hole[1])])


