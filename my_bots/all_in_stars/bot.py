"""Equity computations from the rank tables (pure NumPy; used by the bot, LBR and the arena).

All ranges are float arrays over the 1326 combos. Combos that overlap known cards are ignored.
"""




UNIFORM = np.ones(NUM_COMBOS)


def runout_boards(board, dead, max_runouts: int = 0, rng=None) -> np.ndarray:
    """All (or a random subset of) completions of `board` to 5 cards avoiding `dead`. Shape (R, 5)."""
    board = [int(c) for c in board]
    used = set(board) | {int(c) for c in dead}
    rest = [c for c in range(52) if c not in used]
    need = 5 - len(board)
    if need == 0:
        return np.array([board], dtype=np.int64)
    if need >= 3 or (max_runouts and _ncomb(len(rest), need) > max_runouts):
        n = max_runouts or 500
        rng = rng or np.random.default_rng()
        rest_a = np.array(rest, dtype=np.int64)
        idx = np.argsort(rng.random((n, rest_a.size)), axis=1)[:, :need]
        extra = rest_a[idx]
    else:
        extra = np.array(list(itertools.combinations(rest, need)), dtype=np.int64)
    return np.hstack([np.tile(np.array(board, dtype=np.int64), (extra.shape[0], 1)), extra])


def _ncomb(n, k):
    from math import comb
    return comb(n, k)


def ranks_on_boards(tables: Tables, boards: np.ndarray) -> np.ndarray:
    """(R, 1326) uint16 ranks of every combo on every 5-card board (65535 = blocked)."""
    cid, perm = tables.canon_many(boards)
    rows = np.asarray(tables.river_rank[cid])            # (R, 1326) in canonical suits
    return np.take_along_axis(rows, PERM_COMBO[perm].astype(np.int64), axis=1)


def equity_vs_range(tables: Tables, hole, board, opp_range=None, max_runouts: int = 600, rng=None) -> float:
    """P(win) + P(tie)/2 of `hole` against an opponent range over the remaining runouts."""
    h = combo_index(hole[0], hole[1])
    w = (UNIFORM if opp_range is None else np.asarray(opp_range, dtype=np.float64)).copy()
    w[(COMBO_MASK & np.uint64(cards_mask(list(hole) + list(board)))) != 0] = 0.0
    if w.sum() <= 0:
        return 0.5
    boards = runout_boards(board, hole, max_runouts, rng)
    ranks = ranks_on_boards(tables, boards)                # (R, 1326)
    mine = ranks[:, h][:, None]
    valid = ranks != 65535
    ww = w[None, :] * valid                                # runout cards may block opponent combos
    win = (ww * (ranks < mine)).sum(axis=1)
    tie = (ww * (ranks == mine)).sum(axis=1)
    tot = ww.sum(axis=1)
    return float(((win + 0.5 * tie) / np.maximum(tot, 1e-12)).mean())


def equity_multi(tables: Tables, hole, board, weights: np.ndarray, runouts: int = 100, rng=None) -> np.ndarray:
    """Showdown equity of `hole` vs each row of weights (K, 1326) over shared run-outs -> float[K]."""
    boards = runout_boards(board, hole, runouts, rng)
    ranks = ranks_on_boards(tables, boards)                     # (R, 1326)
    mine = ranks[:, combo_index(hole[0], hole[1])][:, None]
    valid = (ranks != 65535).astype(np.float64)
    win = (ranks < mine) * valid
    tie = (ranks == mine) * valid
    w = np.atleast_2d(np.asarray(weights, dtype=np.float64)).T  # (1326, K)
    w = w * ((COMBO_MASK & np.uint64(cards_mask(list(hole) + list(board)))) == 0)[:, None]
    num = win @ w + 0.5 * (tie @ w)                              # (R, K)
    den = valid @ w
    eq = np.where(den > 0, num / np.where(den > 0, den, 1.0), 0.5)
    return eq.mean(axis=0)


def river_strengths(tables: Tables, board) -> np.ndarray:
    """EHS of every combo on a full board vs. a uniformly random opponent hand (card removal exact).

    Returns float64[1326] (NaN for combos that overlap the board).
    """
    ranks = tables.river_ranks(board).astype(np.int64)
    out = np.full(NUM_COMBOS, np.nan)
    idx = np.flatnonzero(ranks != 65535)
    r = ranks[idx]
    rs = np.sort(r)
    less = np.searchsorted(rs, r, side="left")            # opponents ranked lower (before card removal)
    leq = np.searchsorted(rs, r, side="right")
    cards = COMBO_CARDS[idx].astype(np.int64)
    less_c = np.zeros((52, idx.size), dtype=np.int64)
    leq_c = np.zeros((52, idx.size), dtype=np.int64)
    count_c = np.zeros(52, dtype=np.int64)
    for c in np.unique(cards):
        rc = np.sort(r[(cards[:, 0] == c) | (cards[:, 1] == c)])
        count_c[c] = rc.size
        less_c[c] = np.searchsorted(rc, r, side="left")
        leq_c[c] = np.searchsorted(rc, r, side="right")
    a, b = cards[:, 0], cards[:, 1]
    cols = np.arange(idx.size)
    # inclusion-exclusion over opponents containing card a or card b (only the combo itself has both)
    lower = less - less_c[a, cols] - less_c[b, cols]
    equal = (leq - less) - (leq_c[a, cols] - less_c[a, cols]) - (leq_c[b, cols] - less_c[b, cols]) + 1
    n_opp = idx.size - count_c[a] - count_c[b] + 1
    out[idx] = (lower + 0.5 * equal) / n_opp
    return out


