"""Card, hand-combo, board and suit-permutation encodings (pure Python + NumPy).

Card c in 0..51:  c = 4 * rank + suit,  rank 0..12 = 2..A,  suit 0..3 = c, d, h, s.
Combos:           the 1326 unordered hole-card pairs (c1 < c2), in lexicographic order.
Boards:           k-card sets ranked by colex index, a bijection onto 0 .. C(52, k) - 1.
Suit permutation: SUIT_PERMS[p][s] is the image of suit s; index 0 is the identity.
"""



RANKS = "23456789TJQKA"
SUITS = "cdhs"
NUM_CARDS = 52
NUM_COMBOS = 1326
NUM_PREFLOP_CLASSES = 169


def make_card(rank: int, suit: int) -> int:
    return 4 * rank + suit


def card_rank(c: int) -> int:
    return int(c) >> 2


def card_suit(c: int) -> int:
    return int(c) & 3


def parse_card(text: str) -> int:
    t = text.strip()
    if t.startswith("10"):
        t = "T" + t[2:]
    if len(t) != 2:
        raise ValueError(f"bad card {text!r}")
    return make_card(RANKS.index(t[0].upper()), SUITS.index(t[1].lower()))


def parse_cards(cards) -> list:
    """'AsKd', 'As Kd', ['As', 'Kd'] or [51, 46] -> list of card ints."""
    if isinstance(cards, str):
        s = cards.replace(" ", "").replace(",", "")
        return [parse_card(s[i:i + 2]) for i in range(0, len(s), 2)]
    return [int(c) if isinstance(c, (int, np.integer)) else parse_card(c) for c in cards]


def card_str(c: int) -> str:
    return RANKS[int(c) >> 2] + SUITS[int(c) & 3]


def cards_str(cards) -> str:
    return "".join(card_str(c) for c in cards)


def cards_mask(cards) -> int:
    m = 0
    for c in cards:
        m |= 1 << int(c)
    return m


# --- hole-card combos ------------------------------------------------------------------
COMBO_CARDS = np.zeros((NUM_COMBOS, 2), dtype=np.int16)
COMBO_INDEX = np.full((NUM_CARDS, NUM_CARDS), -1, dtype=np.int16)
_k = 0
for _i in range(NUM_CARDS):
    for _j in range(_i + 1, NUM_CARDS):
        COMBO_CARDS[_k] = (_i, _j)
        COMBO_INDEX[_i, _j] = COMBO_INDEX[_j, _i] = _k
        _k += 1
del _i, _j, _k

COMBO_MASK = (np.uint64(1) << COMBO_CARDS[:, 0].astype(np.uint64)) | (
    np.uint64(1) << COMBO_CARDS[:, 1].astype(np.uint64))

# CARD_COMBOS[c] = the 51 combo indices that contain card c
CARD_COMBOS = np.array(
    [sorted(int(COMBO_INDEX[c, d]) for d in range(NUM_CARDS) if d != c) for c in range(NUM_CARDS)],
    dtype=np.int16)


def combo_index(c1: int, c2: int) -> int:
    return int(COMBO_INDEX[int(c1), int(c2)])


def blocked_combos(cards) -> np.ndarray:
    """bool[1326]: True where the combo shares a card with `cards`."""
    return (COMBO_MASK & np.uint64(cards_mask(cards))) != 0


# --- colex ranking of boards --------------------------------------------------------------
BINOM = np.array([[comb(n, k) for k in range(8)] for n in range(NUM_CARDS + 1)], dtype=np.int64)


def colex_index(cards) -> int:
    s = sorted(int(c) for c in cards)
    return int(sum(int(BINOM[c, i + 1]) for i, c in enumerate(s)))


def colex_index_many(boards: np.ndarray) -> np.ndarray:
    """Row-wise colex index of an (N, k) array of boards (rows need not be sorted)."""
    b = np.sort(np.asarray(boards, dtype=np.int64), axis=1)
    out = np.zeros(b.shape[0], dtype=np.int64)
    for i in range(b.shape[1]):
        out += BINOM[b[:, i], i + 1]
    return out


def colex_unrank(idx: int, k: int) -> list:
    out = []
    for i in range(k, 0, -1):
        c = i - 1
        while BINOM[c + 1, i] <= idx:
            c += 1
        out.append(c)
        idx -= int(BINOM[c, i])
    return sorted(out)


# --- suit permutations --------------------------------------------------------------------
SUIT_PERMS = np.array(list(itertools.permutations(range(4))), dtype=np.int8)       # (24, 4)
PERM_CARD = np.array([[4 * (c >> 2) + int(p[c & 3]) for c in range(NUM_CARDS)] for p in SUIT_PERMS],
                     dtype=np.int16)                                                   # (24, 52)
PERM_COMBO = COMBO_INDEX[PERM_CARD[:, COMBO_CARDS[:, 0]], PERM_CARD[:, COMBO_CARDS[:, 1]]]  # (24, 1326)


# --- preflop strategic classes (169, lossless under suit symmetry) --------------------------
def preflop_class(c1: int, c2: int) -> int:
    """13x13 grid: pair -> (r, r); suited -> (hi, lo); offsuit -> (lo, hi)."""
    r1, r2 = int(c1) >> 2, int(c2) >> 2
    hi, lo = max(r1, r2), min(r1, r2)
    if r1 == r2:
        return 13 * hi + hi
    if (int(c1) & 3) == (int(c2) & 3):
        return 13 * hi + lo
    return 13 * lo + hi


def preflop_class_name(k: int) -> str:
    r, c = divmod(int(k), 13)
    if r == c:
        return RANKS[r] * 2
    if r > c:
        return RANKS[r] + RANKS[c] + "s"
    return RANKS[c] + RANKS[r] + "o"


PREFLOP_CLASS = np.array([preflop_class(a, b) for a, b in COMBO_CARDS], dtype=np.int16)
PREFLOP_CLASS_NAMES = [preflop_class_name(k) for k in range(NUM_PREFLOP_CLASSES)]


