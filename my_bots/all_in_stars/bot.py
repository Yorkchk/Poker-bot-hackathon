# pokerbot/runtime/translate.py
# =================================================================================================
"""Action translation between the real game and the abstract tree.

Bet sizes are compared as pot fractions: (raise_to - opponent contribution) / (pot + amount to call),
so the mapping does not depend on chip units or on earlier translation errors.
Off-tree opponent sizes use the pseudo-harmonic mapping (Ganzfried & Sandholm, IJCAI 2013):
for A < x < B, P(map to A) = (B - x)(1 + A) / ((B - A)(1 + x)).
"""



def pseudo_harmonic(x: float, a: float, b: float) -> float:
    """Probability of mapping size x to the smaller size a (a <= x <= b)."""
    if b <= a:
        return 1.0
    if x <= a:
        return 1.0
    if x >= b:
        return 0.0
    return (b - x) * (1.0 + a) / ((b - a) * (1.0 + x))


def pot_fraction(raise_to: float, contrib_me: float, contrib_opp: float) -> float:
    """Size of a raise to `raise_to` by `me` as a fraction of the pot after calling."""
    to_call = contrib_opp - contrib_me
    pot = contrib_me + contrib_opp
    return (raise_to - contrib_opp) / max(pot + to_call, 1e-9)


def map_size(x: float, sizes: List[float], allin_index: int = -1, is_allin: bool = False) -> List[Tuple[int, float]]:
    """Map a real pot-fraction size onto indices of `sizes` (sorted ascending): [(index, prob), ...].

    An all-in maps to the abstract all-in if one exists.
    """
    if not sizes:
        return []
    if is_allin and allin_index >= 0:
        return [(allin_index, 1.0)]
    if x <= sizes[0]:
        return [(0, 1.0)]
    if x >= sizes[-1]:
        return [(len(sizes) - 1, 1.0)]
    for i in range(len(sizes) - 1):
        a, b = sizes[i], sizes[i + 1]
        if a <= x <= b:
            pa = pseudo_harmonic(x, a, b)
            out = []
            if pa > 0:
                out.append((i, pa))
            if pa < 1:
                out.append((i + 1, 1.0 - pa))
            return out
    return [(len(sizes) - 1, 1.0)]


