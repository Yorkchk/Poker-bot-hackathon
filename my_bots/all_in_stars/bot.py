def _opp_stats(game_state, me):
    """The opponent's raw rates in vf's profile (fed whichever bot plays): {stat: (rate, chances)}."""
    opp = next((p.get("bot_id") for p in game_state.get("players") or []
                if p.get("bot_id") != me and p.get("state") != "busted"), None)
    if opp is None or _BOT is None:
        return {k: (0.0, 0) for k in _STATS}
    prof = _BOT.profiles.get(opp)
    return {k: (prof.count[k] / prof.chances[k] if prof.chances[k] else 0.0, prof.chances[k]) for k in _STATS}


def _bp_flags():
    try:
        return set(BOT.agent.model.flags())
    except Exception:
        return set()


def _rate(st, stat, n_min):
    rate, n = st[stat]
    return rate if n >= n_min else None


def _looks_strong(st):
    """vf-like: joins many hands, rarely raises before the flop, bets or raises (rather than calls)
    after it, folds to bets. bp-like: raises many hands before the flop, still folds to bets."""
    h = HYBRID
    vpip, pfr = _rate(st, "vpip", h["min_hands"]), _rate(st, "pfr", h["min_hands"])
    aggr, fold = _rate(st, "aggression", h["min_spots"]), _rate(st, "fold_to_bet", h["min_spots"])
    fold_few = _rate(st, "fold_to_bet", h["bp_spots"])
    vf_like = (None not in (vpip, pfr, aggr, fold) and vpip >= h["vf_vpip"] and pfr <= h["vf_pfr"]
               and aggr >= h["vf_aggr"] and fold >= h["vf_fold"])
    bp_like = (None not in (vpip, pfr, fold_few) and pfr >= h["bp_pfr"] and vpip >= h["bp_vpip"]
               and fold_few >= h["bp_fold"])
    return bool(vf_like or bp_like)


def _is_caller(st):
    fold, pfr = _rate(st, "fold_to_bet", HYBRID["min_spots"]), _rate(st, "pfr", HYBRID["min_hands"])
    return fold is not None and fold <= HYBRID["caller_fold"] and (pfr is None or pfr < HYBRID["bp_pfr"])


def _is_maniac(st):
    pfr, fold_few = _rate(st, "pfr", HYBRID["min_hands"]), _rate(st, "fold_to_bet", 3)
    if pfr is not None and (pfr >= HYBRID["maniac_pfr"] or
                            (pfr >= HYBRID["bp_pfr"] and fold_few is not None and fold_few <= HYBRID["maniac_fold"])):
        return True
    return bool(_bp_flags() & {"maniac", "random", "station"})


def _looks_weak(st):
    """Clearly not a strong bot: tight (joins few hands), a caller or a maniac."""
    vpip = _rate(st, "vpip", HYBRID["min_hands"])
    return (vpip is not None and vpip < HYBRID["tight_vpip"]) or _is_caller(st) or _is_maniac(st)


def _choose(st):
    """Which bot plays the next hand (policies that switch between hands)."""
    pol = HYBRID["policy"]
    if pol in ("vf", "bp"):
        return pol
    if pol == "fold_switch":
        rate, n = st["fold_to_bet"]
        if n < HYBRID["min_spots"]:
            return _ACTIVE
        if _ACTIVE == "vf" and rate >= HYBRID["to_bp_fold"]:
            return "bp"
        if _ACTIVE == "bp" and rate < HYBRID["to_vf_fold"]:
            return "vf"
        return _ACTIVE
    if pol == "classify":
        if _looks_weak(st):
            return "vf"
        if _looks_strong(st):
            return HYBRID.get("strong_bot", "bp")
        return _ACTIVE
    return _ACTIVE


def _guard(game_state, st, bp_reply):
    """vf's reply where its exploit disagrees with bp against this opponent, else None."""
    vf_reply = vf_decide(game_state)
    if not isinstance(vf_reply, dict) or not isinstance(bp_reply, dict):
        return None
    a_bp, a_vf = bp_reply.get("action"), vf_reply.get("action")
    if game_state.get("street") != "preflop" and _is_caller(st):
        if (a_bp in _AGGRESSIVE) != (a_vf in _AGGRESSIVE):     # bluff into / check behind a caller
            return vf_reply
    if a_bp == "fold" and a_vf != "fold" and _is_maniac(st):
        return vf_reply
    return None


def decide(game_state):
    """Called by the tournament for every decision (and once with {"type": "warmup"})."""
    global _ACTIVE, _ACTIVE_HAND, _BOT, _TAKEOVER
    try:
        if game_state.get("type") == "warmup":
            try:
                _BP_DECIDE(game_state)
            except Exception:
                pass
            return {"action": "check"}
        me = game_state.get("your_bot_id") or "me"
        if _BOT is None:
            _BOT = BOT_CLASS(name=me, config=SUBMISSION_CONFIG, rng=random.Random(random.getrandbits(64)))
        try:
            _feed_finished_hands(game_state, _BOT, me)      # vf's profiles, whichever bot plays
        except Exception:
            pass
        st = _opp_stats(game_state, me)
        hand = game_state.get("hand_num")
        if hand != _ACTIVE_HAND:                            # switch only between hands
            _ACTIVE_HAND = hand
            _ACTIVE = _choose(st)
        pol = HYBRID["policy"]
        if pol == "split":
            who = HYBRID["pre"] if game_state.get("street") == "preflop" else HYBRID["post"]
        elif pol == "guard":
            who = "vf" if _TAKEOVER == hand else "bp"
        else:
            who = _ACTIVE
        if who == "split":                                  # bp before the flop, vf after it
            who = "bp" if game_state.get("street") == "preflop" else "vf"
        if who == "bp":
            reply = _BP_DECIDE(game_state)
            if pol == "guard":
                alt = _guard(game_state, st, reply)
                if alt is not None:
                    _TAKEOVER, who, reply = hand, "vf", alt
                    try:
                        BOT.agent.pending = None            # bp's proposed action was not played
                    except Exception:
                        pass
        else:
            reply = vf_decide(game_state)
        if isinstance(reply, dict):
            debug = reply.get("debug") if isinstance(reply.get("debug"), dict) else {}
            extra = {"bot": who}
            if HYBRID.get("probe"):
                extra["st"] = {k: [round(r, 3), n] for k, (r, n) in st.items()}
                extra["fl"] = sorted(_bp_flags())
            reply["debug"] = dict(debug, **extra)
        return reply
    except Exception:
        return {"action": "check"} if game_state.get("can_check") else {"action": "fold"}
