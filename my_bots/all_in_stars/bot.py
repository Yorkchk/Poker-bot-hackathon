"""Step 3: opponent profiles, built from recorded hands.

Every stat is a count of "times they did X" over "times they had the chance".
Small samples are pulled towards a typical value: the estimate behaves as if
we had already seen PRIOR_WEIGHT imaginary hands of an average player, so a
few hands can't swing it wildly.

Every stat exists twice:
  get(stat)         long memory: all hands count equally
  get_recent(stat)  short memory: each older chance counts a bit less (a chance
                    RECENT_HALF_LIFE chances ago counts half), so a bot that
                    changes style shows up here within a few dozen hands
"""



PRIOR_WEIGHT = 20
RECENT_HALF_LIFE = 25                          # in chances of that stat
RECENT_DECAY = 0.5 ** (1 / RECENT_HALF_LIFE)
RECENT_PRIOR_WEIGHT = 4      # short memory holds ~36 chances; a bigger pull would mask real styles

# name: (typical value, description)
STATS = {
    "vpip":          (0.30, "joins hands (puts chips in voluntarily before the flop)"),
    "pfr":           (0.15, "raises before the flop"),
    "threebet":      (0.07, "re-raises before the flop when someone already raised"),
    "fold_to_raise": (0.55, "folds before the flop when facing a raise"),
    "aggression":    (0.45, "share of after-flop actions that are bets/raises (vs calls)"),
    "fold_to_bet":   (0.45, "folds after the flop when facing a bet"),
    "cbet":          (0.60, "bets the flop after raising before it"),
    "wtsd":          (0.30, "reaches showdown after seeing the flop"),
    "wsd":           (0.50, "wins at showdown"),
}


class Profile:
    def __init__(self, player):
        self.player = player
        self.hands = 0
        self.count = Counter()      # times they did it
        self.chances = Counter()    # times they could have
        self.recent_count = Counter()     # same, but older chances fade out
        self.recent_chances = Counter()
        self.fold_by_street = defaultdict(lambda: [0, 0])  # street -> [folds, chances]
        self.bet_sizes = Counter()  # "flop 3/4" -> times
        self.shown = []             # [{"hand_id", "cards", "board", "actions"}]

    def get(self, stat):
        typical = STATS[stat][0]
        return (self.count[stat] + typical * PRIOR_WEIGHT) / (self.chances[stat] + PRIOR_WEIGHT)

    def get_recent(self, stat):
        typical = STATS[stat][0]
        return ((self.recent_count[stat] + typical * RECENT_PRIOR_WEIGHT)
                / (self.recent_chances[stat] + RECENT_PRIOR_WEIGHT))

    def _mark(self, stat, did):
        self.chances[stat] += 1
        if did:
            self.count[stat] += 1
        self.recent_count[stat] = self.recent_count[stat] * RECENT_DECAY + (1 if did else 0)
        self.recent_chances[stat] = self.recent_chances[stat] * RECENT_DECAY + 1

    # ---- snapshot (restart support): plain dicts, JSON-friendly
    SHOWN_IN_SNAPSHOT = 50

    def to_dict(self):
        return {
            "hands": self.hands,
            "count": dict(self.count), "chances": dict(self.chances),
            "recent_count": dict(self.recent_count), "recent_chances": dict(self.recent_chances),
            "fold_by_street": {k: list(v) for k, v in self.fold_by_street.items()},
            "bet_sizes": dict(self.bet_sizes),
            # shown hands without their action lists, to keep the file small
            "shown": [{k: v for k, v in s.items() if k != "actions"}
                      for s in self.shown[-self.SHOWN_IN_SNAPSHOT:]],
        }

    @classmethod
    def from_dict(cls, player, d):
        p = cls(player)
        p.hands = d["hands"]
        p.count, p.chances = Counter(d["count"]), Counter(d["chances"])
        p.recent_count, p.recent_chances = Counter(d["recent_count"]), Counter(d["recent_chances"])
        for k, v in d.get("fold_by_street", {}).items():
            p.fold_by_street[k] = list(v)
        p.bet_sizes = Counter(d.get("bet_sizes", {}))
        p.shown = list(d.get("shown", []))
        return p

    def summary(self):
        parts = [f"{self.player}: {self.hands} hands"]
        for stat in ("vpip", "pfr", "threebet", "aggression", "fold_to_bet", "cbet", "wtsd", "wsd"):
            parts.append(f"{stat} {self.get(stat):.0%} ({self.chances[stat]})")
        lines = [" | ".join(parts)]
        if self.bet_sizes:
            total = sum(self.bet_sizes.values())
            top = ", ".join(f"{k} {v / total:.0%}" for k, v in self.bet_sizes.most_common(5))
            lines.append(f"    bet sizes: {top}")
        lines.append(f"    reading: {self.reading()}")
        return "\n".join(lines)

    def reading(self):
        notes = []
        vpip, pfr, agg, ftb = self.get("vpip"), self.get("pfr"), self.get("aggression"), self.get("fold_to_bet")
        notes.append("loose" if vpip > 0.45 else "tight" if vpip < 0.2 else "medium")
        notes.append("aggressive" if agg > 0.6 or pfr > 0.3 else "passive" if agg < 0.3 else "balanced")
        if ftb > 0.6:
            notes.append("folds a lot -> bluff it")
        elif ftb < 0.3:
            notes.append("rarely folds -> don't bluff, bet good hands big")
        return ", ".join(notes)


class Profiles:
    def __init__(self, me=None):
        self.me = me
        self.by_player = {}

    def get(self, player):
        if player not in self.by_player:
            self.by_player[player] = Profile(player)
        return self.by_player[player]

    def add_hand(self, hand):
        """Update profiles from one recorded hand (see history.py for the format)."""
        me = hand.get("me") or self.me
        actions = hand.get("actions") or []
        players = [p["id"] for p in hand.get("players") or []]
        for a in actions:
            if a.get("player") not in players:
                players.append(a.get("player"))
        players = [p for p in players if p is not None and p != me]

        state = {p: {"vpip": False, "pfr": False, "preflop_acted": False, "folded_pre": False,
                     "saw_flop": False, "flop_acted": False} for p in players}
        last_pre_raiser = None
        flop_bet_made = False

        for ctx in replay(actions):
            p = ctx["player"]
            prev_raiser = last_pre_raiser
            if ctx["street"] == "preflop" and ctx["action"] == "raise":
                last_pre_raiser = p
            if p not in state or not ctx["voluntary"]:
                continue
            s, prof, kind, street = state[p], self.get(p), ctx["action"], ctx["street"]

            if street == "preflop":
                s["preflop_acted"] = True
                if kind in ("call", "raise"):
                    s["vpip"] = True
                if kind == "raise":
                    s["pfr"] = True
                facing_raise = ctx["raises_before"] >= 1 and prev_raiser != p
                if facing_raise and ctx["raises_before"] == 1:
                    prof._mark("threebet", kind == "raise")
                if facing_raise:
                    prof._mark("fold_to_raise", kind == "fold")
                if kind == "fold":
                    s["folded_pre"] = True
            else:
                if kind in ("raise", "call"):
                    prof._mark("aggression", kind == "raise")
                if ctx["facing_bet"]:
                    prof._mark("fold_to_bet", kind == "fold")
                    fs = prof.fold_by_street[street]
                    fs[1] += 1
                    fs[0] += kind == "fold"
                if street == "flop" and not s["flop_acted"] and p == last_pre_raiser and not flop_bet_made:
                    prof._mark("cbet", kind == "raise")
                if street == "flop":
                    s["flop_acted"] = True
                if kind == "raise":
                    prof.bet_sizes[f"{street} {size_bucket(ctx['size'])}"] += 1
            if street == "flop" and kind == "raise":
                flop_bet_made = True

        board = hand.get("board") or []
        shown = hand.get("shown") or {}
        result = hand.get("result") or {}
        complete = hand.get("complete", False)
        for p in players:
            s, prof = state[p], self.get(p)
            prof.hands += 1
            if s["preflop_acted"]:
                prof._mark("vpip", s["vpip"])
                prof._mark("pfr", s["pfr"])
            saw_flop = len(board) >= 3 and s["preflop_acted"] and not s["folded_pre"]
            if complete and saw_flop:
                prof._mark("wtsd", p in shown)
            if complete and p in shown:
                prof._mark("wsd", result.get(p, 0) > 0)
                prof.shown.append({"hand_id": hand.get("hand_id"), "cards": shown[p],
                                   "board": board, "actions": actions})
                del prof.shown[:-200]

    def summary(self):
        return "\n".join(self.by_player[p].summary() for p in sorted(self.by_player))

    def to_dict(self):
        return {p: prof.to_dict() for p, prof in self.by_player.items()}

    @classmethod
    def from_dict(cls, d, me=None):
        profiles = cls(me=me)
        for p, pd in d.items():
            profiles.by_player[p] = Profile.from_dict(p, pd)
        return profiles


