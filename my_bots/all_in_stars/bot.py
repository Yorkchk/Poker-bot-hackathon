"""Real-time river subgame solver: vectorised range-vs-range Discounted CFR (pure NumPy).

The subgame starts at the current real state (exact pot, stacks and the opponent's actual bet) with
both players' current ranges. Information sets are (node, hand).

Layout (built once per solve): for each player p, all its decision nodes' regrets live in one matrix
R_p of shape (hands_p, total actions of p) with a column block per node, so regret matching,
discounting and average-strategy updates are single vectorised operations. Reach and value
propagation are done level by level (a handful of NumPy calls per tree level). Leaves are evaluated
with one matrix product each: showdown values S_pq @ reach_q and fold values C_pq @ reach_q
(S = sign(rank_p - rank_q) on card-compatible pairs, C = card compatibility).
DCFR (alpha=1.5, beta=0, gamma=2), alternating updates. Exploitability (NashConv / 2) is exact
within the subgame's bet tree.
"""





DEC, LEAF_FOLD, LEAF_SD = 0, 1, 2


@dataclass
class RiverSizes:
    bet: tuple = (0.33, 0.75, 1.25)
    raises: tuple = (1.0,)
    max_raises: int = 2
    allin: bool = True
    allin_snap: float = 0.7
    min_weight: float = 1e-5        # combos below this share of the range are dropped


class _Node:
    __slots__ = ("kind", "player", "parent", "children", "action", "contrib", "value_scale", "state", "depth",
                 "aidx")

    def __init__(self, kind, player, parent, action, contrib, depth, aidx):
        self.kind = kind
        self.player = player
        self.parent = parent
        self.children: List[int] = []
        self.action = action
        self.contrib = contrib
        self.value_scale = 0.0
        self.state = None
        self.depth = depth
        self.aidx = aidx


def _raise_targets(s: HandState, sizes: RiverSizes) -> List[int]:
    rb = s.raise_bounds()
    if rb is None or s.num_raises >= sizes.max_raises:
        return []
    lo, hi = rb
    fr = sizes.bet if s.num_raises == 0 else sizes.raises
    me = s.to_act
    out = set()
    for f in fr:
        a = max(lo, min(hi, s.raise_to_for_fraction(f)))
        if a - s.contrib[me] >= sizes.allin_snap * s.stack_left(me):
            a = hi
        out.add(a)
    if sizes.allin:
        out.add(hi)
    return sorted(out)


class RiverSolver:
    def __init__(self, tables, board, root: HandState, ranges, sizes: Optional[RiverSizes] = None,
                 extra_root_sizes=(), dtype=np.float32):
        if root.street != RIVER or root.finished:
            raise ValueError("river solver needs an unfinished river state")
        self.sizes = sizes or RiverSizes()
        self.dtype = dtype
        self.board = tuple(int(c) for c in board)
        bmask = np.uint64(cards_mask(self.board))
        ranks_all = tables.river_ranks(self.board).astype(np.int64)
        self.idx, self.w = [], []
        for s in (0, 1):
            r = np.asarray(ranges[s], dtype=np.float64).copy()
            r[(COMBO_MASK & bmask) != 0] = 0.0
            tot = r.sum()
            if tot <= 0:
                raise ValueError(f"empty range for seat {s}")
            r /= tot
            keep = np.flatnonzero(r > self.sizes.min_weight)
            self.idx.append(keep)
            self.w.append((r[keep] / r[keep].sum()).astype(dtype))
        self.ranks = [ranks_all[self.idx[0]], ranks_all[self.idx[1]]]
        m0 = COMBO_MASK[self.idx[0]][:, None]
        m1 = COMBO_MASK[self.idx[1]][None, :]
        self.compat01 = ((m0 & m1) == 0).astype(dtype)
        self.sd01 = (np.sign(self.ranks[0][:, None] - self.ranks[1][None, :]).astype(dtype) * self.compat01)
        self.root_state = root.copy()
        self.pot0 = root.pot
        self._build(root, extra_root_sizes)
        self._layout()
        self._prefix = [self._prefix_tables(p) for p in (0, 1)]
        self.leaf_mode = "prefix"
        self.iterations = 0
        self.solve_seconds = 0.0

    def _prefix_tables(self, p: int) -> dict:
        """Index tables for O(n log n) leaf evaluation of player p's hands against player q's reach."""
        q = 1 - p
        rp, rq = self.ranks[p], self.ranks[q]
        cards_p = COMBO_CARDS[self.idx[p]].astype(np.int64)
        cards_q = COMBO_CARDS[self.idx[q]].astype(np.int64)
        order = np.argsort(rq, kind="stable")
        rs = rq[order]
        t = {"order": order, "less": np.searchsorted(rs, rp, "left"), "leq": np.searchsorted(rs, rp, "right")}
        # q's hands grouped by card (each hand appears under both of its cards), rank-sorted within a card
        concat, seg_start, seg_end = [], np.zeros(52, np.int64), np.zeros(52, np.int64)
        seg_ranks = {}
        for c in range(52):
            mem = np.flatnonzero((cards_q[:, 0] == c) | (cards_q[:, 1] == c))
            mem = mem[np.argsort(rq[mem], kind="stable")]
            seg_start[c] = len(concat)
            concat.extend(mem.tolist())
            seg_end[c] = len(concat)
            seg_ranks[c] = rq[mem]
        t["concat"] = np.array(concat, dtype=np.int64)
        for name, side in (("less", "left"), ("leq", "right")):
            for k in (0, 1):
                pos = np.empty(rp.size, np.int64)
                for c in np.unique(cards_p[:, k]):
                    m = cards_p[:, k] == c
                    pos[m] = seg_start[c] + np.searchsorted(seg_ranks[c], rp[m], side)
                t[f"{name}{k}"] = pos
        t["start0"], t["start1"] = seg_start[cards_p[:, 0]], seg_start[cards_p[:, 1]]
        t["end0"], t["end1"] = seg_end[cards_p[:, 0]], seg_end[cards_p[:, 1]]
        where = {int(c): i for i, c in enumerate(self.idx[q])}
        self_idx = np.array([where.get(int(c), -1) for c in self.idx[p]], dtype=np.int64)
        t["self_idx"], t["self_ok"] = np.maximum(self_idx, 0), (self_idx >= 0)
        return t

    def _prefix_leaves(self, p: int, reach_q: np.ndarray, V: np.ndarray) -> None:
        t = self._prefix[p]
        dt = self.dtype
        if self.sd_leaves.size:
            R = reach_q[:, self.sd_leaves]                                   # (n_q, T)
            C = np.zeros((R.shape[0] + 1, R.shape[1]), dtype=dt)
            np.cumsum(R[t["order"]], axis=0, out=C[1:])
            G = np.zeros((t["concat"].size + 1, R.shape[1]), dtype=dt)
            np.cumsum(R[t["concat"]], axis=0, out=G[1:])
            win = C[t["less"]] - (G[t["less0"]] - G[t["start0"]]) - (G[t["less1"]] - G[t["start1"]])
            lose = (C[-1] - C[t["leq"]]) - (G[t["end0"]] - G[t["leq0"]]) - (G[t["end1"]] - G[t["leq1"]])
            V[:, self.sd_leaves] = (win - lose) * self.sd_scale
        if self.fold_leaves.size:
            R = reach_q[:, self.fold_leaves]
            G = np.zeros((t["concat"].size + 1, R.shape[1]), dtype=dt)
            np.cumsum(R[t["concat"]], axis=0, out=G[1:])
            card0 = G[t["end0"]] - G[t["start0"]]
            card1 = G[t["end1"]] - G[t["start1"]]
            same = R[t["self_idx"]] * t["self_ok"][:, None]
            V[:, self.fold_leaves] = (R.sum(axis=0) - card0 - card1 + same) * self.fold_scale[p]

    # -- tree ----------------------------------------------------------------------------------
    def _build(self, root: HandState, extra_root_sizes) -> None:
        self.nodes: List[_Node] = []
        stack = [(root.copy(), -1, None, 0, -1, tuple(extra_root_sizes))]
        while stack:
            s, parent, action, depth, aidx, extra = stack.pop()
            nid = len(self.nodes)
            if parent >= 0:
                self.nodes[parent].children[aidx] = nid
            if s.finished:
                if s.folded >= 0:
                    n = _Node(LEAF_FOLD, s.folded, parent, action, tuple(s.contrib), depth, aidx)
                    n.value_scale = float(s.contrib[s.folded])
                else:
                    n = _Node(LEAF_SD, -1, parent, action, tuple(s.contrib), depth, aidx)
                    n.value_scale = float(min(s.contrib))
                self.nodes.append(n)
                continue
            n = _Node(DEC, s.to_act, parent, action, tuple(s.contrib), depth, aidx)
            n.state = s
            self.nodes.append(n)
            acts = []
            if s.can_fold():
                acts.append(Action(FOLD))
            acts.append(Action(CALL))
            targets = set(_raise_targets(s, self.sizes))
            rb = s.raise_bounds()
            if rb is not None:
                for f in extra:
                    targets.add(max(rb[0], min(rb[1], s.raise_to_for_fraction(f))))
            acts += [Action(RAISE, a) for a in sorted(targets)]
            n.children = [-1] * len(acts)
            for k in reversed(range(len(acts))):
                c = s.copy()
                c.apply(acts[k])
                stack.append((c, nid, acts[k], depth + 1, k, ()))
        self.dec_nodes = [i for i, n in enumerate(self.nodes) if n.kind == DEC]
        self.sd_leaves = np.array([i for i, n in enumerate(self.nodes) if n.kind == LEAF_SD], dtype=np.int64)
        self.fold_leaves = np.array([i for i, n in enumerate(self.nodes) if n.kind == LEAF_FOLD], dtype=np.int64)

    def _layout(self) -> None:
        N = len(self.nodes)
        nodes = self.nodes
        self.N = N
        self.sd_scale = np.array([nodes[i].value_scale for i in self.sd_leaves], dtype=self.dtype)
        self.fold_scale = [np.array([(-1.0 if nodes[i].player == p else 1.0) * nodes[i].value_scale
                                     for i in self.fold_leaves], dtype=self.dtype) for p in (0, 1)]
        # per-player column layout
        self.col_start = {}
        self.p_nodes = [[], []]
        for i in self.dec_nodes:
            self.p_nodes[nodes[i].player].append(i)
        self.ncols = [0, 0]
        self.col_node = [None, None]     # node owning each column
        self.col_child = [None, None]    # child reached by each column
        self.seg = [None, None]          # reduceat segment starts
        self.nact = [None, None]
        for p in (0, 1):
            cn, cc, seg, na = [], [], [], []
            for i in self.p_nodes[p]:
                self.col_start[i] = len(cn)
                seg.append(len(cn))
                na.append(len(nodes[i].children))
                for c in nodes[i].children:
                    cn.append(i)
                    cc.append(c)
            self.ncols[p] = len(cn)
            self.col_node[p] = np.array(cn, dtype=np.int64)
            self.col_child[p] = np.array(cc, dtype=np.int64)
            self.seg[p] = np.array(seg, dtype=np.int64)
            self.nact[p] = np.array(na, dtype=np.int64)
        # sigma column used to reach each node (for its parent's player), -1 at root
        self.sig_col = np.full(N, -1, dtype=np.int64)
        for i in range(1, N):
            par = nodes[i].parent
            self.sig_col[i] = self.col_start[par] + nodes[i].aidx
        # levels
        maxd = max(n.depth for n in nodes)
        self.levels = []
        for d in range(1, maxd + 1):
            idx = np.array([i for i in range(N) if nodes[i].depth == d], dtype=np.int64)
            par = np.array([nodes[i].parent for i in idx], dtype=np.int64)
            ppl = np.array([nodes[nodes[i].parent].player for i in idx], dtype=np.int64)
            self.levels.append((idx, par, ppl, self.sig_col[idx]))
        # bottom-up: decision nodes per depth with concatenated children
        self.up_levels = []
        for d in range(maxd - 1, -1, -1):
            dec = [i for i in self.dec_nodes if nodes[i].depth == d]
            if not dec:
                continue
            ch, seg, pl, cols = [], [], [], []
            for i in dec:
                seg.append(len(ch))
                for c in nodes[i].children:
                    ch.append(c)
                    pl.append(nodes[i].player)
                    cols.append(self.sig_col[c])
            self.up_levels.append((np.array(dec, dtype=np.int64), np.array(ch, dtype=np.int64),
                                   np.array(seg, dtype=np.int64), np.array(pl, dtype=np.int64),
                                   np.array(cols, dtype=np.int64),
                                   np.array([nodes[i].player for i in dec], dtype=np.int64)))
        # column index of each p-column within the player's matrix (sigma lookups by global sig_col)
        self.R = [np.zeros((self.w[p].size, self.ncols[p]), dtype=self.dtype) for p in (0, 1)]
        self.S = [np.zeros((self.w[p].size, self.ncols[p]), dtype=self.dtype) for p in (0, 1)]
        self.uniform = [np.repeat(1.0 / self.nact[p], self.nact[p])[None, :].astype(self.dtype)
                        if self.ncols[p] else None for p in (0, 1)]

    # -- vectorised building blocks ----------------------------------------------------------
    def _normalise(self, p: int, M: np.ndarray) -> np.ndarray:
        if self.ncols[p] == 0:
            return M
        pos = np.maximum(M, 0.0)
        sums = np.add.reduceat(pos, self.seg[p], axis=1)
        den = np.repeat(sums, self.nact[p], axis=1)
        return np.where(den > 0, pos / np.where(den > 0, den, 1.0), self.uniform[p])

    def _sigma(self, average: bool):
        return [self._normalise(p, self.S[p] if average else self.R[p]) for p in (0, 1)]

    def _reach(self, p: int, sig_p: np.ndarray) -> np.ndarray:
        reach = np.empty((self.w[p].size, self.N), dtype=self.dtype)
        reach[:, 0] = self.w[p]
        for idx, par, ppl, cols in self.levels:
            reach[:, idx] = reach[:, par]
            m = ppl == p
            if m.any():
                reach[:, idx[m]] *= sig_p[:, cols[m]]
        return reach

    def _values(self, p: int, sig_p: np.ndarray, reach_q: np.ndarray, best_response: bool = False) -> np.ndarray:
        V = np.zeros((self.w[p].size, self.N), dtype=self.dtype)
        if self.leaf_mode == "prefix":
            self._prefix_leaves(p, reach_q, V)
        else:
            if self.sd_leaves.size:
                M = self.sd01 if p == 0 else -self.sd01.T
                V[:, self.sd_leaves] = (M @ reach_q[:, self.sd_leaves]) * self.sd_scale
            if self.fold_leaves.size:
                C = self.compat01 if p == 0 else self.compat01.T
                V[:, self.fold_leaves] = (C @ reach_q[:, self.fold_leaves]) * self.fold_scale[p]
        for dec, ch, seg, pl, cols, dpl in self.up_levels:
            CV = V[:, ch]
            mine = pl == p
            if best_response:
                s = np.add.reduceat(CV, seg, axis=1)
                mx = np.maximum.reduceat(CV, seg, axis=1)
                V[:, dec] = np.where((dpl == p)[None, :], mx, s)
            else:
                if mine.any():
                    CV = CV.copy()
                    CV[:, mine] *= sig_p[:, cols[mine]]
                V[:, dec] = np.add.reduceat(CV, seg, axis=1)
        return V

    def iterate(self, n_iter: int = 1, alpha: float = 1.5, beta: float = 0.0, gamma: float = 2.0) -> None:
        for _ in range(n_iter):
            self.iterations += 1
            t = float(self.iterations)
            sig = self._sigma(average=False)
            reach = [self._reach(0, sig[0]), self._reach(1, sig[1])]
            for p in (0, 1):
                if p == 1:   # alternating updates: player 0's strategy changed, player 1's did not
                    sig[0] = self._normalise(0, self.R[0])
                    reach[0] = self._reach(0, sig[0])
                if self.ncols[p] == 0:
                    continue
                V = self._values(p, sig[p], reach[1 - p])
                self.R[p] += V[:, self.col_child[p]] - V[:, self.col_node[p]]
                self.S[p] += reach[p][:, self.col_node[p]] * sig[p]
            pos_f = self.dtype(t ** alpha / (t ** alpha + 1.0))
            neg_f = self.dtype(t ** beta / (t ** beta + 1.0))
            avg_f = self.dtype((t / (t + 1.0)) ** gamma)
            for p in (0, 1):
                R = self.R[p]
                R *= np.where(R > 0, pos_f, neg_f)
                self.S[p] *= avg_f

    def solve(self, iterations: int = 300, time_limit: Optional[float] = None, check_every: int = 10) -> "RiverSolver":
        """Run up to `iterations`; with a time limit, stop before the predicted next chunk would exceed it."""
        t0 = time.perf_counter()
        done = 0
        k = 2 if time_limit is not None else check_every
        while done < iterations:
            k = min(k, iterations - done)
            self.iterate(k)
            done += k
            if time_limit is not None:
                el = time.perf_counter() - t0
                per_it = el / done
                remaining = time_limit - el
                if remaining <= per_it:
                    break
                k = max(1, min(check_every, int(remaining / per_it) - 1))
        self.solve_seconds += time.perf_counter() - t0
        return self

    # -- results --------------------------------------------------------------------------------
    def exploitability(self) -> dict:
        avg = self._sigma(average=True)
        reach = [self._reach(0, avg[0]), self._reach(1, avg[1])]
        w = [x.astype(np.float64) for x in self.w]
        z = float(w[0] @ self.compat01.astype(np.float64) @ w[1])
        br = []
        for p in (0, 1):
            V = self._values(p, avg[p], reach[1 - p], best_response=True)
            br.append(float(w[p] @ V[:, 0].astype(np.float64)) / z)
        ev0 = float(w[0] @ self._values(0, avg[0], reach[1])[:, 0].astype(np.float64)) / z
        nash_conv = br[0] + br[1]
        return {"nash_conv": nash_conv, "exploitability": nash_conv / 2.0,
                "pct_pot": 100.0 * nash_conv / 2.0 / self.pot0, "ev_seat0": ev0, "br": br,
                "iterations": self.iterations, "seconds": self.solve_seconds}

    def average_strategy(self, node: int) -> np.ndarray:
        p = self.nodes[node].player
        c0 = self.col_start[node]
        n = len(self.nodes[node].children)
        a = self.S[p][:, c0:c0 + n].astype(np.float64)
        tot = a.sum(axis=1, keepdims=True)
        return np.where(tot > 0, a / np.where(tot > 0, tot, 1.0), 1.0 / n)

    def actions(self, node: int = 0) -> List[Action]:
        return [self.nodes[c].action for c in self.nodes[node].children]

    def hand_strategy(self, combo: int, node: int = 0) -> np.ndarray:
        """Average strategy of the player to act at `node` for one combo (uniform if not in range)."""
        p = self.nodes[node].player
        pos = np.flatnonzero(self.idx[p] == combo)
        if pos.size == 0:
            return np.full(len(self.nodes[node].children), 1.0 / len(self.nodes[node].children))
        return self.average_strategy(node)[pos[0]]

    def range_update(self, node: int, action_index: int) -> np.ndarray:
        """float[1326] factor sigma(action | combo) for the player at `node` (0 outside its range)."""
        p = self.nodes[node].player
        f = np.zeros(NUM_COMBOS)
        f[self.idx[p]] = self.average_strategy(node)[:, action_index]
        return f

    def map_action(self, node: int, kind: int, amount: int):
        """[(child index, prob)] for a real action at `node` (pseudo-harmonic for off-tree raises)."""
        n = self.nodes[node]
        acts = self.actions(node)
        if kind in (FOLD, CALL):
            return [(i, 1.0) for i, a in enumerate(acts) if a.kind == kind][:1]
        s = n.state
        me = s.to_act
        rs = [(i, pot_fraction(a.amount, s.contrib[me], s.contrib[1 - me]), a.amount >= s.cfg.stack)
              for i, a in enumerate(acts) if a.kind == RAISE]
        if not rs:
            return []
        x = pot_fraction(amount, s.contrib[me], s.contrib[1 - me])
        allin_idx = next((j for j, r in enumerate(rs) if r[2]), -1)
        return [(rs[j][0], p) for j, p in map_size(x, [r[1] for r in rs], allin_idx, amount >= s.cfg.stack)]


